# `api:` feature lines. Both suffixes have to come off: capa-rules writes

# `- api: CreateFile = description` and also `- api: syscall # https://man7...`,

# and a regex that strips only the first captured the URL as part of an API

# name on the first run of this.

_API = re.compile(r"^\s*-?\s*api:\s*(.+?)\s*$", re.M)

def api_names(rules_dir: Path) -> set[str]:

    """Every distinct `api:` feature in capa-rules, cleaned."""

    out: set[str] = set()

    for path in rules_dir.rglob("*.yml"):

        text = path.read_text(errors="replace")

        for raw in _API.findall(text):

            name = raw.split("#")[0].split(" = ")[0].strip()

            if name:

                out.add(name)

    return out

def _trim_dll_part(api: str) -> str:

    """`capa.rules.trim_dll_part`, imported when capa is installed.

    Reimplemented only as a fallback, because this generator must agree with

    capa exactly: if our idea of a rule's bare name differs from capa's, we

    generate hooks for names capa never looks for.

    """

    try:

        from capa.rules import trim_dll_part  # noqa: PLC0415

        return trim_dll_part(api)

    except Exception:

        if ".#" in api:

            return api

        if api.count(".") == 1 and "::" not in api:

            return api.split(".")[1]

        return api

# --- Windows ---------------------------------------------------------------

# apimon locates a DLL through its VAD and reads its export table, so anything

# that never maps as a user-mode DLL cannot be hooked by it. `ntoskrn` is a

# typo in capa-rules (for `ntoskrnl`), kept here so it is filtered rather than

# silently emitted as `ntoskrn.dll`.

KERNEL_MODULES = frozenset({"ntoskrnl", "ntoskrn", "fwpkclnt", "fltmgr",

                            "ndis", "hal", "ci", "netio"})

# The Speakeasy phnt signatures are ntdll declarations. Do not infer that
# arbitrary kernel-mode functions can be hooked through apimon.
NTDLL_PREFIXES = ("Nt", "Zw", "Rtl", "Ldr", "Csr", "Dbg")

# Clearly kernel-only names cannot be hooked as user-mode exports. Do not
# turn a capa module hint into a fabricated DLL (e.g. kernel32!KeInsertQueueApc).
KERNEL_ONLY_PREFIXES = ("Ke", "Ki", "FsRtl")
# Android/Bionic APIs sometimes appear in multi-platform capa rules, but
# they cannot be presumed to exist in both Microsoft CRT libraries.
NON_WINDOWS_CRT = frozenset({"__android_log_print", "__system_property_get"})

# Speakeasy format=2 uses compact type codes. Only DRAKVUF's recognised
# printers below cause typed dereferences; other tokens use the base printer.
# Never decode a string from an OUT-only buffer at hook entry.
def apimon_type(param: list) -> str:
    """Map a Speakeasy [name, type_code, flags, ...] to an apimon type."""
    code = param[1]
    flags = param[2] if len(param) > 2 else ""
    out_only = "o" in flags and "i" not in flags

    if code == "s" and not out_only:
        return "lpcstr"
    if code == "S" and not out_only:
        return "lpcwstr"
    if code == "ps:UNICODE_STRING" and not out_only:
        return "punicode_string"
    if code in ("p:g", "ps:GUID") and not out_only:
        return "refiid"
    if code in ("p:u32", "p:i32") and not out_only:
        return "pulong"
    if code in ("p:u64", "p:i64") and not out_only:
        return "pulonglong"
    if code == "p:p" and not out_only:
        return "lpvoid*"
    # LPArray represents a pointer to an array, not a scalar.
    if code == "a" or code.startswith("a:"):
        return "lpvoid"
    if code in ("p", "h", "s", "S") or code.startswith(("p:", "ps:")):
        return "lpvoid"
    return "dword"


def signature_arguments(fn: dict, arch: str = "x64") -> tuple[str, str]:
    """Return (DRAKVUF arguments, reason), never inventing parameter slots.

    A Speakeasy `skip` does *not* automatically mean its parameters are invalid:
    e.g. an unsupported return type does not affect the input ABI. However,
    phnt can *omit* a parameter it failed to parse, so such skips are unsafe.
    """
    params = fn.get("params")
    if not isinstance(params, list):
        return "", "no parameter metadata"
    if fn.get("variadic"):
        return "", "variadic (unsafe to fix arity)"
    reason = str(fn.get("skip", ""))
    if reason and not reason.startswith("return type:"):
        return "", f"Speakeasy skip: {reason}"
    if not params:
        return "", "zero parameters (verified)"

    fields = []
    for idx, p in enumerate(params):
        if not isinstance(p, list) or len(p) < 2 or not isinstance(p[1], str):
            return "", "malformed parameter metadata"
        code = p[1]
        kind = code.split(":", 1)[0]
        if kind in ("g", "arr", "f32", "f64"):
            return "", f"unsupported argument ABI: {code}"
        if arch == "x86" and kind in ("u64", "i64"):
            return "", f"64-bit by-value argument on x86: {code}"
        if kind == "st":
            # A four-byte COORD or similar value takes one integer argument
            # slot on Win64 and on x86. Larger x86 aggregates take several
            # slots; larger Win64 aggregates are passed by reference, but
            # their accurate handling needs a separate explicit override.
            try:
                width = code.split(":", 2)[2]
                width = width.split("/")[0 if arch == "x86" else -1]
                size = int(width)
            except (IndexError, ValueError):
                return "", f"unknown by-value aggregate size: {code}"
            if size > (4 if arch == "x86" else 8):
                return "", f"by-value aggregate needs special ABI handling: {code}"
        name = p[0] if isinstance(p[0], str) else ""
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            name = f"Arg{idx}"
        fields.append(f"{name}:{apimon_type(p)}")
    return ",".join(fields), "Speakeasy parameter metadata"


def arg_list(fn: dict, arch: str = "x64") -> str:
    """Compatibility wrapper: one safe named token per argument."""
    return signature_arguments(fn, arch)[0]


def signature_dir(speakeasy: Path) -> Path:
    """Allow a checkout, installed package, or resources/win32 directory."""
    candidates = (
        speakeasy,
        speakeasy / "resources" / "win32",
        speakeasy / "speakeasy" / "resources" / "win32",
    )
    filenames = ("win32json_signatures.json.gz", "phnt_signatures.json.gz")
    for directory in candidates:
        if all((directory / name).is_file() for name in filenames):
            return directory
    raise ValueError(
        f"Speakeasy signature archives not found under {speakeasy}. "
        "Generate both with scripts/gen_win32_signatures.py and "
        "scripts/gen_phnt_signatures.py in the Speakeasy checkout."
    )


def load_speakeasy(
    speakeasy: Path, arch: str = "x64"
) -> tuple[dict[str, tuple[str, str]], str, dict[str, str]]:
    """Return API -> (DLL, named args), source versions, and diagnostic status.

    On duplicate declarations choose a usable signature over one that has
    unusable metadata, preserving source precedence for equal quality.
    """
    directory = signature_dir(speakeasy)
    by_name: dict[str, tuple[str, str]] = {}
    statuses: dict[str, str] = {}
    versions: list[str] = []
    for filename, expected_source in (
        ("win32json_signatures.json.gz", "win32json"),
        ("phnt_signatures.json.gz", "phnt"),
    ):
        with gzip.open(directory / filename, "rt", encoding="utf-8") as stream:
            doc = json.load(stream)
        if doc.get("format") != 2 or not isinstance(doc.get("functions"), dict):
            raise ValueError(f"Invalid Speakeasy signature format in {filename}: expected format=2")
        if doc.get("source") != expected_source:
            raise ValueError(f"Unexpected signature source in {filename}: {doc.get('source')!r}")
        revision = doc.get("commit") or doc.get("version") or "UNRECORDED"
        versions.append(f"{expected_source} {str(revision)[:12]}")
        for name, signatures in sorted(doc["functions"].items()):
            if expected_source == "phnt" and not name.startswith(NTDLL_PREFIXES):
                continue
            if not isinstance(signatures, list):
                continue
            viable = []
            for sig in signatures:
                if not isinstance(sig, dict):
                    continue
                supported_arch = sig.get("arch")
                if supported_arch and arch not in supported_arch:
                    continue
                dll = sig.get("dll")
                if not isinstance(dll, str) or not dll:
                    continue
                dll = dll.lower()
                if not dll.endswith(".dll"):
                    dll += ".dll"
                if dll.rsplit(".", 1)[0] in KERNEL_MODULES or is_api_set_contract(dll):
                    continue
                args, status = signature_arguments(sig, arch)
                viable.append((dll, args, status))
            if not viable:
                continue
            # If metadata is unusable, other declarations or phnt may work.
            best = next((v for v in viable if v[1]), viable[0])
            previous = by_name.get(name)
            if previous is None or (not previous[1] and best[1]):
                by_name[name] = (best[0], best[1])
                statuses[name] = f"{expected_source}: {best[2]}"
    return by_name, ", ".join(versions), statuses


def apply_extra_signatures(path: Path, by_name: dict[str, tuple[str, str]],
                           statuses: dict[str, str]) -> None:
    """Load explicitly reviewed signatures without pretending they are Speakeasy.

    Format: {"dll!Function": ["Name:type", ...]}. An empty list explicitly
    represents zero arguments. Overrides only missing or untyped signatures.
    """
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("--extra-signatures must be a JSON object")
    for qualified, fields in data.items():
        if not isinstance(qualified, str) or "!" not in qualified:
            raise ValueError(f"Invalid signature key: {qualified!r}")
        dll, name = qualified.rsplit("!", 1)
        if not dll or not name or not isinstance(fields, list):
            raise ValueError(f"Invalid extra signature: {qualified}")
        stem = dll.lower().removesuffix(".dll")
        if stem in KERNEL_MODULES or is_api_set_contract(dll):
            raise ValueError(f"Non-physical DLL in extra signature: {qualified}")
        for token in fields:
            if not isinstance(token, str) or not re.fullmatch(
                r"[A-Za-z_][A-Za-z0-9_]*:[A-Za-z0-9_*]+", token
            ):
                raise ValueError(f"Invalid DRAKVUF argument token in {qualified}: {token!r}")
        existing = by_name.get(name)
        if existing is None or not existing[1]:
            by_name[name] = (f"{stem}.dll", ",".join(fields))
            statuses[name] = "reviewed extra signature" + (" (zero parameters)" if not fields else "")


# --- xwin / libclang SDK fallback ------------------------------------------
# This is intentionally a standalone ctypes wrapper over libclang's stable C
# interface. It does not require Python's `clang` bindings and never uses a
# regular expression to infer C parameter lists.

import ctypes
import ctypes.util
import os


class _CXString(ctypes.Structure):
    _fields_ = [("data", ctypes.c_void_p), ("private_flags", ctypes.c_uint)]


class _CXCursor(ctypes.Structure):
    _fields_ = [("kind", ctypes.c_int), ("xdata", ctypes.c_int),
                ("data", ctypes.c_void_p * 3)]


class _CXType(ctypes.Structure):
    _fields_ = [("kind", ctypes.c_int), ("data", ctypes.c_void_p * 2)]


class _CXSourceLocation(ctypes.Structure):
    """CXSourceLocation ABI from clang-c/Index.h."""
    _fields_ = [("ptr_data", ctypes.c_void_p * 2), ("int_data", ctypes.c_uint)]


class _CXUnsavedFile(ctypes.Structure):
    _fields_ = [("filename", ctypes.c_char_p), ("contents", ctypes.c_char_p),
                ("length", ctypes.c_ulong)]


class _LibClang:
    """The tiny subset of libclang's C API needed for named prototypes."""

    _visitor_type = ctypes.CFUNCTYPE(ctypes.c_uint, _CXCursor,
                                     _CXCursor, ctypes.c_void_p)

    def __init__(self, explicit: Path | None = None):
        candidates = []
        if explicit:
            candidates.append(str(explicit))
        if os.environ.get("LIBCLANG_LIBRARY_FILE"):
            candidates.append(os.environ["LIBCLANG_LIBRARY_FILE"])
        installed = ctypes.util.find_library("clang")
        if installed:
            candidates.append(installed)
        candidates.extend(str(p) for root in (
            Path("/usr/local/swift/usr/lib"), Path("/usr/local/lib"),
            Path("/usr/lib"), Path("/opt/homebrew/opt/llvm/lib"),
        ) for p in root.glob("libclang.so*"))
        candidates.extend(str(p) for p in sorted(
            Path("/usr/lib").glob("llvm-*/lib/libclang.so*"), reverse=True))
        errors = []
        for candidate in dict.fromkeys(candidates):
            try:
                self.lib = ctypes.CDLL(candidate)
                self.path = candidate
                break
            except OSError as e:
                errors.append(f"{candidate}: {e}")
                if explicit:
                    raise RuntimeError(f"Cannot load explicitly requested --libclang {explicit}: {e}") from e
        else:
            raise RuntimeError("Could not load libclang. Install libclang-dev or set "
                               "--libclang /path/to/libclang.so. " + "; ".join(errors[-2:]))
        l = self.lib
        self._bind("clang_createIndex", ctypes.c_void_p, ctypes.c_int, ctypes.c_int)
        self._bind("clang_disposeIndex", None, ctypes.c_void_p)
        self._bind("clang_parseTranslationUnit", ctypes.c_void_p,
                   ctypes.c_void_p, ctypes.c_char_p,
                   ctypes.POINTER(ctypes.c_char_p), ctypes.c_int,
                   ctypes.POINTER(_CXUnsavedFile), ctypes.c_uint, ctypes.c_uint)
        self._bind("clang_disposeTranslationUnit", None, ctypes.c_void_p)
        self._bind("clang_getTranslationUnitCursor", _CXCursor, ctypes.c_void_p)
        self._bind("clang_visitChildren", ctypes.c_uint, _CXCursor,
                   self._visitor_type, ctypes.c_void_p)
        self._bind("clang_getCursorSpelling", _CXString, _CXCursor)
        self._bind("clang_getCursorLocation", _CXSourceLocation, _CXCursor)
        self._bind("clang_getSpellingLocation", None, _CXSourceLocation,
                   ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_uint),
                   ctypes.POINTER(ctypes.c_uint), ctypes.POINTER(ctypes.c_uint))
        self._bind("clang_getFileName", _CXString, ctypes.c_void_p)
        self._bind("clang_getCursorType", _CXType, _CXCursor)
        self._bind("clang_getResultType", _CXType, _CXType)
        self._bind("clang_getFunctionTypeCallingConv", ctypes.c_uint, _CXType)
        self._bind("clang_Cursor_getNumArguments", ctypes.c_int, _CXCursor)
        self._bind("clang_Cursor_getArgument", _CXCursor, _CXCursor, ctypes.c_uint)
        self._bind("clang_isFunctionTypeVariadic", ctypes.c_uint, _CXType)
        self._bind("clang_getCanonicalType", _CXType, _CXType)
        self._bind("clang_getPointeeType", _CXType, _CXType)
        self._bind("clang_getTypeSpelling", _CXString, _CXType)
        self._bind("clang_Type_getSizeOf", ctypes.c_longlong, _CXType)
        self._bind("clang_isConstQualifiedType", ctypes.c_uint, _CXType)
        self._bind("clang_getNumDiagnostics", ctypes.c_uint, ctypes.c_void_p)
        self._bind("clang_getDiagnostic", ctypes.c_void_p, ctypes.c_void_p, ctypes.c_uint)
        self._bind("clang_getDiagnosticSeverity", ctypes.c_uint, ctypes.c_void_p)
        self._bind("clang_getDiagnosticSpelling", _CXString, ctypes.c_void_p)
        self._bind("clang_disposeDiagnostic", None, ctypes.c_void_p)
        self._bind("clang_getCString", ctypes.c_char_p, _CXString)
        self._bind("clang_disposeString", None, _CXString)

    def _bind(self, name, restype, *argtypes):
        fn = getattr(self.lib, name)
        fn.argtypes = argtypes
        fn.restype = restype

    def string(self, value: _CXString) -> str:
        try:
            raw = self.lib.clang_getCString(value)
            return raw.decode("utf-8", "replace") if raw else ""
        finally:
            self.lib.clang_disposeString(value)

    def declaration_file(self, cursor: _CXCursor) -> str:
        """Return the header containing the actual function declaration.

        Clang may see CRT declarations while processing an umbrella header
        such as Windows.h. Attributing them to the umbrella header makes
        genuine CRT APIs appear to have no safe owner (or gives them a fake
        Windows.h owner). CXFile spelling location identifies the real header.
        """
        file = ctypes.c_void_p()
        line = ctypes.c_uint()
        column = ctypes.c_uint()
        offset = ctypes.c_uint()
        location = self.lib.clang_getCursorLocation(cursor)
        self.lib.clang_getSpellingLocation(
            location, ctypes.byref(file), ctypes.byref(line),
            ctypes.byref(column), ctypes.byref(offset))
        if not file.value:
            return ""
        return self.string(self.lib.clang_getFileName(file))

    def type_code(self, arg: _CXCursor, arch: str) -> str | None:
        t = self.lib.clang_getCursorType(arg)
        name = self.string(self.lib.clang_getTypeSpelling(t))
        canonical = self.lib.clang_getCanonicalType(t)
        full_name = name.replace(" ", "").upper()
        if full_name in {"LPCWSTR", "PCWSTR", "LPCOLESTR", "PCZZWSTR"}:
            return "S"
        if full_name in {"LPCSTR", "PCSTR", "PCZZSTR"}:
            return "s"
        # CXType_Pointer=101, BlockPointer=102, LValueReference=103;
        # pointers to functions and typedefs canonicalize to POINTER.
        if canonical.kind in (101, 102, 103, 104):
            pointee = self.lib.clang_getPointeeType(canonical)
            pname = self.string(self.lib.clang_getTypeSpelling(pointee)).lower()
            if self.lib.clang_isConstQualifiedType(pointee):
                if re.search(r"\b(?:wchar_t|wchar|olechar|unsigned short)\b", pname):
                    return "S"
                if re.search(r"\b(?:char|signed char|unsigned char)\b", pname):
                    return "s"
            return "p"
        # Only array types decay to pointers. CXType_Vector=113 is NOT an
        # array and may use XMM registers, so never classify it as a pointer.
        if canonical.kind in (112, 114, 115, 116):
            return "p"
        if canonical.kind == 113:
            return None
        if canonical.kind == 105:  # CXType_Record, struct by value
            size = self.lib.clang_Type_getSizeOf(canonical)
            if size <= 0 or size > (4 if arch == "x86" else 8):
                return None  # ABI-sensitive: fail closed rather than guess.
            typename = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_") or "Record"
            return f"st:{typename}:{size}"
        # Only integer-like scalars use the slots read by DRAKVUF apimon.
        # CXType_Float=21, Double=22, LongDouble=23, Half/Float128=30..32
        # use XMM/FP registers on common Windows ABIs. Guessing by sizeof()
        # creates fake Number features; fail closed instead.
        if canonical.kind not in (*range(3, 21), 106):  # integer and enum
            return None
        size = self.lib.clang_Type_getSizeOf(canonical)
        if size not in (1, 2, 4, 8):
            return None
        if size == 8 and arch == "x86":
            return None  # Multiple stack slots with this apimon ABI.
        if size == 8:
            return "u64"
        return "u32"

    def return_code(self, function_type: _CXType) -> str:
        t = self.lib.clang_getResultType(function_type)
        if t.kind == 2:  # CXType_Void
            return "v"
        canonical = self.lib.clang_getCanonicalType(t)
        if canonical.kind in (101, 102, 103, 104):
            return "p"
        size = self.lib.clang_Type_getSizeOf(canonical)
        return {1: "u8", 2: "u16", 4: "u32", 8: "u64"}.get(size, "p")

    def parse(self, headers: list[Path], include_dirs: list[Path],
              targets: set[str], arch: str) -> tuple[dict[str, dict], list[str]]:
        """Parse a small batch of headers. Reject the whole TU on errors."""
        # These includes live in an unsaved translation unit under /tmp.
        # Relative includes would therefore be resolved against /tmp, not
        # against the directory from which the generator was executed.
        headers = [h.expanduser().resolve(strict=True) for h in headers]
        include_dirs = [d.expanduser().resolve(strict=True) for d in include_dirs]
        # Individual Windows SDK headers are NOT standalone translation units.
        # In particular WinBase.h, Psapi.h, wininet.h and winnt.h rely on types
        # introduced by Windows.h. Include it first for SDK (not CRT) headers.
        um_dirs = [d for d in include_dirs if d.name.lower() == 'um']
        windows_h = next((d / n for d in um_dirs for n in ('Windows.h', 'windows.h')
                          if (d / n).is_file()), None)
        sdk_header = any('/sdk/include/' in h.as_posix().lower() for h in headers)
        prelude = ([windows_h] if sdk_header and windows_h and
                   all(h.resolve() != windows_h.resolve() for h in headers) else [])
        source = "".join(f'#include "{h.as_posix()}"\n' for h in prelude + headers)
        srcname = b"/tmp/__drakvuf_xwin_prototypes__.c"
        content = source.encode()
        unsaved = _CXUnsavedFile(srcname, content, len(content))
        opts = ["-x", "c", "-target", (
            "i686-pc-windows-msvc" if arch == "x86" else "x86_64-pc-windows-msvc"),
            "-fms-extensions", "-fms-compatibility", "-ferror-limit=8",
            "-D_WIN32_WINNT=0x0A00", "-DWINVER=0x0A00",
            # Windows SDK still checks the legacy architecture macros in
            # winnt.h rather than trusting Clang's -target triple.
            "-D_AMD64_=1" if arch == "x64" else "-D_X86_=1"]
        opts.extend(f"-I{d}" for d in include_dirs)
        encoded = [s.encode() for s in opts]
        array = (ctypes.c_char_p * len(encoded))(*encoded)
        l = self.lib
        index = l.clang_createIndex(0, 0)
        tu = None
        try:
            # CXTranslationUnit_SkipFunctionBodies=0x40
            tu = l.clang_parseTranslationUnit(index, srcname, array, len(array),
                                               ctypes.byref(unsaved), 1, 0x40)
            if not tu:
                return {}, [f"libclang did not parse {', '.join(h.name for h in headers)}"]
            errors = []
            for i in range(l.clang_getNumDiagnostics(tu)):
                diag = l.clang_getDiagnostic(tu, i)
                try:
                    if l.clang_getDiagnosticSeverity(diag) >= 3:
                        errors.append(self.string(l.clang_getDiagnosticSpelling(diag)))
                finally:
                    l.clang_disposeDiagnostic(diag)
            if errors:
                return {}, [f"{headers[0].name}: {msg}" for msg in errors[:3]]
            results: dict[str, dict] = {}
            conflicts: set[str] = set()

            def collect(cursor, parent, unused):
                if cursor.kind != 8:  # CXCursor_FunctionDecl
                    return 1  # CXChildVisit_Continue
                name = self.string(l.clang_getCursorSpelling(cursor))
                if name not in targets:
                    return 1
                ft = l.clang_getCursorType(cursor)
                if l.clang_isFunctionTypeVariadic(ft):
                    return 1
                count = l.clang_Cursor_getNumArguments(cursor)
                if count < 0 or count > 64:
                    return 1
                params = []
                for j in range(count):
                    arg = l.clang_Cursor_getArgument(cursor, j)
                    pname = self.string(l.clang_getCursorSpelling(arg))
                    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", pname):
                        return 1  # Names are the goal: do not fabricate Arg0.
                    code = self.type_code(arg, arch)
                    if not code:
                        return 1
                    params.append([pname, code, "i"])
                convention = l.clang_getFunctionTypeCallingConv(ft)
                # CXCallingConv_C=1, X86StdCall=2; do not pretend that
                # fastcall/vectorcall/thiscall are stdcall on 32-bit Windows.
                if arch == "x86" and convention not in (1, 2):
                    return 1
                conv = "cdecl" if arch == "x86" and convention == 1 else "stdcall"
                new = {"params": params, "ret": self.return_code(ft),
                       "conv": conv, "arch": [arch]}
                declaration_file = self.declaration_file(cursor)
                # Header source is diagnostic provenance only, not part of
                # the function signature. Two identical prototypes in
                # different included headers are not a conflict.
                if declaration_file:
                    new["declaration_file"] = declaration_file
                old = results.get(name)
                if old and {k: v for k, v in old.items() if k != "declaration_file"} != {
                        k: v for k, v in new.items() if k != "declaration_file"}:
                    conflicts.add(name)
                elif not old:
                    results[name] = new
                return 1

            callback = self._visitor_type(collect)
            l.clang_visitChildren(l.clang_getTranslationUnitCursor(tu), callback, None)
            for name in conflicts:
                results.pop(name, None)
            warnings = [f"{name}: conflicting declarations in SDK" for name in sorted(conflicts)]
            return results, warnings
        finally:
            if tu:
                l.clang_disposeTranslationUnit(tu)
            l.clang_disposeIndex(index)



# --- xwin import-library cross-check ---------------------------------------
# xwin ships Windows SDK import libraries as well as headers. MSVC COFF short
# import objects include the imported symbol AND an import name. That may be an
# API-set *contract*, not a mapped DLL. Keep only physical host DLLs unless the
# operator explicitly supplies mappings recovered from the guest.
# Physical ownership is stronger
# DLL evidence than the library filename or a random PDB symbol name, but it
# does NOT prove that a particular guest's DLL exports the symbol.


def _coff_import_members(path: Path, arch: str):
    """Yield (function_name, dll) from a COFF archive's short import objects.

    Only code imports from the selected architecture are used. This is not a
    general COFF parser and intentionally ignores normal object files.
    """
    data = path.read_bytes()
    if not data.startswith(b'!<arch>\n'):
        return
    machine = 0x8664 if arch == 'x64' else 0x014c
    offset = 8
    while offset + 60 <= len(data):
        header = data[offset:offset + 60]
        if header[58:60] != b'`\n':
            break
        try:
            size = int(header[48:58].strip())
        except ValueError:
            break
        start = offset + 60
        end = start + size
        if size < 0 or end > len(data):
            break
        member = data[start:end]
        offset = end + (size & 1)
        if len(member) < 22 or member[:4] != b'\x00\x00\xff\xff':
            continue
        try:
            sig1, sig2, version, mach, stamp, data_size, hint, typeinfo = struct.unpack_from('<HHHHIIHH', member)
        except struct.error:
            continue
        # IMPORT_OBJECT_CODE = 0. An import can also represent DATA/CONST.
        if mach != machine or (typeinfo & 3) != 0:
            continue
        names = member[20:].split(b'\0', 3)
        if len(names) < 3:
            continue
        symbol = names[0].decode('utf-8', 'replace')
        dll = names[1].decode('ascii', 'replace').lower()
        if not dll or not dll.endswith('.dll'):
            continue
        if symbol.startswith('__imp_'):
            symbol = symbol[6:]
        # Ignore the underscore/@NN x86 stdcall decoration, not valid
        # leading underscores in literal CRT APIs such as _beginthreadex.
        if arch == 'x86' and symbol.startswith('_') and re.search(r'@\d+$', symbol):
            symbol = re.sub(r'@\d+$', '', symbol[1:])
        if re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', symbol):
            yield symbol, dll


def load_xwin_import_libraries(root: Path, arch: str, wanted: set[str]
                               ) -> tuple[dict[str, set[str]], dict[str, int]]:
    """Find SDK import declarations, NOT verified runtime guest exports."""
    root = root.expanduser().resolve(strict=True)
    dirname = 'x86_64' if arch == 'x64' else 'x86'
    paths = []
    for directory in (root / 'sdk/lib/um' / dirname,
                      root / 'sdk/lib/ucrt' / dirname,
                      root / 'crt/lib' / dirname):
        if directory.is_dir():
            paths += directory.glob('*.lib')
    # xwin installs mixed-case symlinks. Do not scan the same archive twice.
    files = sorted({p.resolve() for p in paths})
    owners: dict[str, set[str]] = {}
    scanned = matched = 0
    for path in files:
        try:
            for name, dll in _coff_import_members(path, arch):
                if name not in wanted:
                    continue
                owners.setdefault(name, set()).add(dll)
                matched += 1
            scanned += 1
        except OSError:
            continue
    return owners, {'libraries': scanned, 'matching_import_members': matched,
                    'distinct_functions': len(owners)}


# API-set imports (api-*/ext-*) are loader *contracts*, not necessarily DLL
# files. Never turn them into DRAKVUF VAD/export hook targets by name.
def is_api_set_contract(dll: str) -> bool:
    stem = dll.lower().removesuffix(".dll")
    return stem.startswith(("api-", "ext-"))


def load_api_set_host_map(path: Path) -> dict[str, str]:
    """Read an operator-supplied mapping obtained from the *target guest*.

    JSON schema: {"api-ms-win-crt-stdio-l1-1-0.dll": "ucrtbase.dll"}.
    This maps a contract to a host DLL, but does not independently establish
    that every function in that contract is exported by that host build.
    """
    doc = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict):
        raise ValueError("--api-set-host-map must contain a JSON object")
    result: dict[str, str] = {}
    valid_dll = re.compile(r"[A-Za-z0-9_.-]+\.dll", re.IGNORECASE)
    for key, val in doc.items():
        if not isinstance(key, str) or not isinstance(val, str):
            raise ValueError(f"non-string API-set host map entry: {key!r}")
        contract = key.lower()
        host = val.lower()
        if not contract.endswith(".dll"):
            contract += ".dll"
        if not host.endswith(".dll"):
            host += ".dll"
        if not is_api_set_contract(contract) or not valid_dll.fullmatch(host):
            raise ValueError(f"invalid API-set mapping: {key!r} -> {val!r}")
        if is_api_set_contract(host) or host.removesuffix(".dll") in KERNEL_MODULES:
            raise ValueError(f"host must be a physical user-mode DLL: {val!r}")
        result[contract] = host
    return result


# --- Guest API-set schema (Windows 10/11 version 6) -------------------------
# The .apiset section of *the target guest's* apisetschema.dll contains the
# contract-to-host mapping. Unambiguous defaults may apply globally; named
# value entries may apply ONLY when the specific importing DLL matches.
# Never turn a contract itself into a hook target. A resolved PE forwarder
# must end at executable code in a supplied guest DLL.

def load_guest_api_set_schema(path: Path, arch: str,
                              importer_hosts_out: dict[tuple[str, str], str] | None = None
                              ) -> tuple[dict[str, str], dict[str, int]]:
    """Read V6 .apiset defaults and optional importer-specific host choices.

    Defaults are returned as a dictionary; trusted context-specific mappings
    can optionally be placed in importer_hosts_out as (contract, DLL) -> host.
    The parser rejects conflicting aliases, unknown versions, and bad bounds.
    """
    data = path.read_bytes()
    if len(data) < 0x100 or data[:2] != b'MZ':
        raise ValueError('not a PE file')

    def read16(offset: int) -> int:
        if offset < 0 or offset + 2 > len(data):
            raise ValueError('truncated PE header')
        return struct.unpack_from('<H', data, offset)[0]

    def read32(offset: int) -> int:
        if offset < 0 or offset + 4 > len(data):
            raise ValueError('truncated PE header')
        return struct.unpack_from('<I', data, offset)[0]

    pe = read32(0x3c)
    if pe + 24 > len(data) or data[pe:pe + 4] != b'PE\x00\x00':
        raise ValueError('invalid PE signature')
    machine = read16(pe + 4)
    wanted = 0x8664 if arch == 'x64' else 0x14c
    if machine != wanted:
        raise ValueError(f'API-set schema PE architecture does not match {arch}')
    sections = read16(pe + 6)
    opt_size = read16(pe + 20)
    sec_base = pe + 24 + opt_size
    if sections > 96 or not sections or sec_base + sections * 40 > len(data):
        raise ValueError('invalid PE sections')
    blob = None
    for index in range(sections):
        offset = sec_base + index * 40
        if data[offset:offset + 8].rstrip(b'\x00') != b'.apiset':
            continue
        virtual_size, _, raw_size, raw_offset = struct.unpack_from('<IIII', data, offset + 8)
        if raw_offset > len(data) or raw_size > len(data) - raw_offset:
            raise ValueError('invalid .apiset section bounds')
        if virtual_size and virtual_size < 28:
            raise ValueError('truncated .apiset namespace')
        blob = data[raw_offset:raw_offset + raw_size]
        break
    if blob is None:
        raise ValueError('PE has no .apiset section (need guest apisetschema.dll)')
    if len(blob) < 28:
        raise ValueError('truncated API-set namespace')
    version, size, flags, count, entry_off, hash_off, hash_factor = struct.unpack_from('<7I', blob)
    if version != 6:
        raise ValueError(f'unsupported API-set namespace version {version}; expected 6')
    if not 28 <= size <= len(blob):
        raise ValueError('invalid API-set namespace size')
    if count > 10000 or entry_off > size or count * 24 > size - entry_off:
        raise ValueError('invalid API-set namespace entry table')

    def take(offset: int, length: int) -> bytes:
        if offset > size or length > size - offset:
            raise ValueError('API-set string/entry outside namespace')
        return blob[offset:offset + length]

    def wide(offset: int, length: int) -> str:
        if length % 2 or length > 8192:
            raise ValueError('invalid API-set UTF-16 length')
        return take(offset, length).decode('utf-16-le').lower()

    mapped: dict[str, str] = {}
    conditional: dict[tuple[str, str], str] = {}
    conflicting_conditionals: set[tuple[str, str]] = set()
    stats = {'entries': count, 'mapped': 0, 'without_default': 0,
             'ambiguous': 0, 'rejected_host': 0, 'conditional_hosts': 0,
             'conditional_conflicts': 0, 'contracts_with_conditionals': 0}
    hostname = re.compile(r'[a-z0-9_.-]+\.dll', re.IGNORECASE)
    importername = re.compile(r'[a-z0-9_.-]+\.(?:dll|exe)', re.IGNORECASE)
    for index in range(count):
        _, name_off, name_len, _, value_off, value_count = struct.unpack_from(
            '<6I', blob, entry_off + index * 24)
        name = wide(name_off, name_len)
        if not is_api_set_contract(name):
            stats['rejected_host'] += 1
            continue
        contract = name if name.endswith('.dll') else name + '.dll'
        if value_count > 128 or value_off > size or value_count * 20 > size - value_off:
            raise ValueError(f'invalid API-set host value table for {contract}')
        defaults: set[str] = set()
        saw_conditional = False
        for v in range(value_count):
            _, alias_off, alias_len, host_off, host_len = struct.unpack_from(
                '<5I', blob, value_off + v * 20)
            # Unlike default mappings, the alias names an importing module.
            # It can safely be used ONLY when the actual forwarder owner matches.
            alias = wide(alias_off, alias_len) if alias_len else ''
            host = wide(host_off, host_len)
            if not host:
                continue
            if not host.endswith('.dll'):
                host += '.dll'
            if (not hostname.fullmatch(host) or is_api_set_contract(host)
                    or host.removesuffix('.dll') in KERNEL_MODULES):
                stats['rejected_host'] += 1
                continue
            if alias:
                saw_conditional = True
                # Normalize only unqualified module basenames, never paths.
                if not alias.endswith(('.dll', '.exe')):
                    alias += '.dll'
                if not importername.fullmatch(alias):
                    stats['rejected_host'] += 1
                    continue
                key = (contract, alias)
                if key in conflicting_conditionals:
                    continue
                if key in conditional and conditional[key] != host:
                    conditional.pop(key)
                    conflicting_conditionals.add(key)
                else:
                    conditional[key] = host
            else:
                defaults.add(host)
        if saw_conditional:
            stats['contracts_with_conditionals'] += 1
        if not defaults:
            stats['without_default'] += 1
            continue
        if len(defaults) > 1:
            stats['ambiguous'] += 1
            continue
        host = next(iter(defaults))
        if (not hostname.fullmatch(host) or is_api_set_contract(host)
                or host.removesuffix('.dll') in KERNEL_MODULES):
            stats['rejected_host'] += 1
            continue
        if contract in mapped and mapped[contract] != host:
            del mapped[contract]
            stats['ambiguous'] += 1
        elif contract not in mapped:
            mapped[contract] = host
    stats['mapped'] = len(mapped)
    stats['conditional_hosts'] = len(conditional)
    stats['conditional_conflicts'] = len(conflicting_conditionals)
    if importer_hosts_out is not None:
        importer_hosts_out.update(conditional)
    return mapped, stats


def combine_guest_api_set_maps(schema_hosts: dict[str, str],
                               operator_hosts: dict[str, str]
                               ) -> tuple[dict[str, str], list[str]]:
    """Merge evidence, rejecting contradictory guest mapping inputs."""
    merged = dict(schema_hosts)
    conflicts = []
    for contract, host in operator_hosts.items():
        if contract in merged and merged[contract] != host:
            conflicts.append(f'{contract}: schema={merged[contract]} vs JSON={host}; disabled')
            del merged[contract]
        else:
            merged[contract] = host
    return merged, conflicts


# --- Guest PE executable exports (stronger evidence than PDB symbols) -------
# Optional. The caller supplies copies of actual target-guest DLLs; neither
# SDK import libraries nor PDB symbols establish physical callable exports.


def _pe_code_exports(path: Path, arch: str,
                     forwarders_out: dict[str, str] | None = None) -> set[str] | None:
    """Read *executable*, named PE exports, excluding forwarded and DATA exports.

    Return None for a non-PE or wrong-architecture image. No external package
    required. Read-only parser; all RVA conversions and lengths are checked.
    """
    data = path.read_bytes()
    if len(data) < 0x100 or data[:2] != b"MZ":
        return None

    def u16(offset: int) -> int:
        if offset < 0 or offset + 2 > len(data):
            raise ValueError("truncated PE u16")
        return struct.unpack_from("<H", data, offset)[0]

    def u32(offset: int) -> int:
        if offset < 0 or offset + 4 > len(data):
            raise ValueError("truncated PE u32")
        return struct.unpack_from("<I", data, offset)[0]

    pe = u32(0x3c)
    if pe + 24 > len(data) or data[pe:pe + 4] != b"PE\x00\x00":
        return None
    machine = u16(pe + 4)
    expected_machine = 0x8664 if arch == "x64" else 0x14c
    if machine != expected_machine:
        return None
    count_sections = u16(pe + 6)
    opt_size = u16(pe + 20)
    opt = pe + 24
    if not 0 < count_sections <= 96 or opt + opt_size > len(data):
        raise ValueError("invalid PE headers")
    magic = u16(opt)
    if magic != (0x20b if arch == 'x64' else 0x10b):
        return None
    directory = opt + (112 if magic == 0x20b else 96)
    if directory + 8 > opt + opt_size:
        raise ValueError("missing export data directory")
    export_rva, export_size = u32(directory), u32(directory + 4)
    sections: list[tuple[int, int, int, int, int]] = []
    for i in range(count_sections):
        sec = opt + opt_size + i * 40
        if sec + 40 > len(data):
            raise ValueError("truncated PE section header")
        virt_size, virt_rva, raw_size, raw_ptr = struct.unpack_from('<IIII', data, sec + 8)
        flags = u32(sec + 36)
        sections.append((virt_rva, max(virt_size, raw_size), raw_ptr, raw_size, flags))

    def rva_offset(rva: int, nbytes: int = 1) -> int:
        for base, _, file_ptr, raw_size, _ in sections:
            delta = rva - base
            if 0 <= delta and delta + nbytes <= raw_size:
                offset = file_ptr + delta
                if offset + nbytes <= len(data):
                    return offset
        raise ValueError(f"invalid/unmapped export RVA: {rva:#x}")

    def code_rva(rva: int) -> bool:
        return any(base <= rva < base + size and (flags & 0x20000000)
                   for base, size, _, _, flags in sections)

    if not export_rva or not export_size:
        return set()
    exp = rva_offset(export_rva, 40)
    num_funcs = u32(exp + 20)
    num_names = u32(exp + 24)
    if num_funcs > 200000 or num_names > 200000:
        raise ValueError("unreasonable export table size")
    func_rva, names_rva, ords_rva = u32(exp + 28), u32(exp + 32), u32(exp + 36)
    funcs = rva_offset(func_rva, num_funcs * 4)
    names = rva_offset(names_rva, num_names * 4)
    ords = rva_offset(ords_rva, num_names * 2)
    exports: set[str] = set()
    for i in range(num_names):
        index = u16(ords + i * 2)
        if index >= num_funcs:
            continue
        target = u32(funcs + index * 4)
        # Export names are shared by code, data, and forwarded exports.
        try:
            name_at = rva_offset(u32(names + i * 4))
            terminator = data.find(b"\x00", name_at, min(len(data), name_at + 512))
            if terminator == -1:
                continue
            name = data[name_at:terminator].decode('ascii')
        except (ValueError, UnicodeDecodeError):
            continue
        if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', name):
            continue
        # A forwarder RVA identifies an export in a *different* DLL. It is
        # not hookable at this RVA, but is useful if the target's real DLL is
        # also supplied. Keep the exact target name, including API-set names.
        if export_rva <= target < export_rva + export_size:
            if forwarders_out is not None:
                try:
                    forward_at = rva_offset(target)
                    max_len = min(512, export_rva + export_size - target)
                    end = data.find(b"\x00", forward_at, forward_at + max_len)
                    if end != -1:
                        forward = data[forward_at:end].decode('ascii')
                        module, dot, sym = forward.rpartition('.')
                        if (dot and re.fullmatch(r'[A-Za-z0-9_.-]+', module)
                                and re.fullmatch(r'(?:[A-Za-z_][A-Za-z0-9_]*|#[0-9]+)', sym)):
                            forwarders_out[name] = forward
                except (ValueError, UnicodeDecodeError):
                    pass
            continue
        if code_rva(target):
            exports.add(name)
    return exports



def locate_mounted_windows_dlls(mount: Path, arch: str) -> Path:
    """Find the correct bitness system directory on a read-only Windows mount.

    x64 System32 holds 64-bit DLLs. On 64-bit Windows, SysWOW64 contains
    32-bit DLLs. Never scan both together: basenames collide across ABIs.
    """
    root = mount.expanduser().resolve(strict=True)
    if not root.is_dir():
        raise ValueError('--guest-windows-root must be a mounted directory')
    folder = 'System32' if arch == 'x64' else 'SysWOW64'
    windows_dirs = [root / 'Windows', root]
    folder_names = [folder] + (['System32'] if arch == 'x86' else [])
    for base in windows_dirs:
        if not base.is_dir():
            continue
        for dirname in folder_names:
            candidate = base / dirname
            if candidate.is_dir() and any(p.name.lower() == 'ntdll.dll' for p in candidate.iterdir()):
                return candidate
    raise ValueError(f'cannot locate Windows/{folder}/ntdll.dll under {root}; '
                     'pass --guest-dlls directly if the image has a nonstandard layout')


def load_guest_dll_exports(root: Path, arch: str,
                           forwarders_out: dict[tuple[str, str], str] | None = None,
                           top_level_only: bool = False
                           ) -> tuple[dict[str, set[str]], dict[str, int], list[str]]:
    """Read a directory of DLLs copied from the target guest (System32/SysWOW64).

    Duplicate DLL basenames with conflicting contents are omitted rather than
    merging potentially incompatible versions of Windows/architecture.
    """
    root = root.expanduser().resolve(strict=True)
    if not root.is_dir():
        raise ValueError("--guest-dlls must point at a directory")
    exports: dict[str, set[str]] = {}
    forwarded: dict[str, dict[str, str]] = {}
    ambiguous: set[str] = set()
    scanned = wrong_arch = rejected = 0
    notices: list[str] = []
    paths = root.iterdir() if top_level_only else root.rglob('*')
    for path in sorted(p for p in paths
                       if p.is_file() and p.suffix.lower() == '.dll'):
        if is_api_set_contract(path.name) or path.name.lower() == 'apisetschema.dll':
            # apisetschema.dll is data/loader metadata, not a hook target.
            continue
        candidate_forwards: dict[str, str] = {}
        try:
            symbols = _pe_code_exports(path, arch, candidate_forwards)
        except (OSError, ValueError) as exc:
            rejected += 1
            if len(notices) < 15:
                notices.append(f"{path.name}: ignored invalid PE exports ({exc})")
            continue
        if symbols is None:
            wrong_arch += 1
            continue
        scanned += 1
        dll = path.name.lower()
        if dll in ambiguous:
            continue
        if dll in exports and (exports[dll] != symbols
                               or forwarded[dll] != candidate_forwards):
            ambiguous.add(dll)
            del exports[dll]
            del forwarded[dll]
            notices.append(f"{dll}: conflicting guest DLL copies; excluded")
        else:
            exports[dll] = symbols
            forwarded[dll] = candidate_forwards
    if forwarders_out is not None:
        for dll, members in forwarded.items():
            for name, target in members.items():
                forwarders_out[(dll, name)] = target
    stats = {'guest_dlls': len(exports), 'parsed': scanned,
             'wrong_arch': wrong_arch, 'invalid': rejected,
             'ambiguous': len(ambiguous),
             'code_exports': sum(len(v) for v in exports.values())}
    return exports, stats, notices



def resolve_guest_pe_forwarders(
    code_exports: dict[str, set[str]],
    forwarded: dict[tuple[str, str], str],
    api_set_hosts: dict[str, str] | None = None,
    importer_hosts: dict[tuple[str, str], str] | None = None,
) -> tuple[dict[tuple[str, str], tuple[str, str]], dict[tuple[str, str], str]]:
    """Follow PE forwarder chains to executable exports in supplied DLLs.

    Resolve API-set contracts via a guest-derived default or an exact match
    for the forwarding DLL as importer. Never use an unrelated importer alias.
    Ordinal-only forwarders and cycles remain unresolved.
    """
    hosts = api_set_hosts or {}
    specific_hosts = importer_hosts or {}
    resolved: dict[tuple[str, str], tuple[str, str]] = {}
    rejected: dict[tuple[str, str], str] = {}

    def chase(key: tuple[str, str], seen: set[tuple[str, str]]
              ) -> tuple[tuple[str, str] | None, str]:
        if key in seen or len(seen) >= 32:
            return None, "cyclic or excessive forwarder chain"
        dll, symbol = key
        if symbol in code_exports.get(dll, set()):
            return key, ""
        raw = forwarded.get(key)
        if raw is None:
            if dll not in code_exports:
                return None, f"target DLL not supplied: {dll}"
            return None, f"{dll} has no named executable export {symbol}"
        module, _, target_name = raw.rpartition('.')
        target_dll = module.lower()
        if not target_dll.endswith('.dll'):
            target_dll += '.dll'
        if target_name.startswith('#'):
            return None, f"ordinal forwarder unsupported: {raw}"
        if is_api_set_contract(target_dll):
            # The forwarding module is the relevant importer context; do not
            # apply an ole32-specific host to other importing DLLs or to xwin
            # import records (where the importer context is unknown).
            specific_host = specific_hosts.get((target_dll, dll))
            host = specific_host or hosts.get(target_dll)
            if not host:
                return None, (f"API-set forwarder {raw} has no applicable host "
                              f"for importer {dll} in the supplied guest schema/map; "
                              "inspect importer-specific API-set values") if (hosts or specific_hosts) else (
                              f"API-set forwarder {raw} needs --api-set-schema or --api-set-host-map")
            target_dll = host
        return chase((target_dll, target_name), seen | {key})

    for key in sorted(forwarded):
        endpoint, error = chase(key, set())
        if endpoint is None:
            rejected[key] = f"{forwarded[key]} ({error})"
        else:
            resolved[key] = endpoint
    return resolved, rejected


# --- Offline Windows-disk candidate discovery ------------------------------
# A mounted NTFS image supplies PE bytes but not loader state. In particular,
# an api-* name in a forwarder refers to an API-set contract; a physical stub
# DLL on disk does not by itself prove that Windows loads that stub. Discover
# possible physical code endpoints, but only opt-in may use such candidates.

def load_disk_apiset_stub_forwarders(root: Path, arch: str, top_level_only: bool = False
                                   ) -> tuple[dict[tuple[str, str], str], Counter]:
    """Read physical api-*/ext-* DLL forwarder records as *hints* only."""
    results: dict[tuple[str, str], str] = {}
    conflicts: set[tuple[str, str]] = set()
    stats: Counter = Counter()
    paths = root.iterdir() if top_level_only else root.rglob('*')
    for path in sorted(p for p in paths
                       if p.is_file() and p.suffix.lower() == '.dll'
                       and is_api_set_contract(p.name)):
        forwarders: dict[str, str] = {}
        try:
            exported = _pe_code_exports(path, arch, forwarders)
        except (OSError, ValueError):
            stats['invalid contract stub files'] += 1
            continue
        if exported is None:
            stats['wrong architecture contract stub files'] += 1
            continue
        stats['physical contract stub files'] += 1
        for name, target in forwarders.items():
            key = path.name.lower(), name
            if key in conflicts:
                continue
            if key in results and results[key].lower() != target.lower():
                results.pop(key)
                conflicts.add(key)
                continue
            results[key] = target
    stats['stub forwarder records'] = len(results)
    stats['conflicting stub records'] = len(conflicts)
    return results, stats


def offline_api_set_forwarder_candidates(
        exports: dict[str, set[str]],
        forwarded: dict[tuple[str, str], str],
        unresolved: dict[tuple[str, str], str],
        disk_stubs: dict[tuple[str, str], str] | None = None,
    ) -> tuple[dict[tuple[str, str], tuple[str, str]],
               dict[tuple[str, str], str], Counter]:
    """Find conservative *possible* same-name code targets, not loader proof.

    Only examine unresolved api-/ext-* PE forwarders whose target API name is
    identical to the original. If a physical stub on the mounted disk names a
    physical implementation, trust it only as an offline candidate and only
    if its executable export is present in the guest corpus. If there is no
    direct stub, require exactly one non-source physical executable exporter.
    Any conflicting stub blocks the candidate rather than selecting by rank.
    """
    disk_stubs = disk_stubs or {}
    found: dict[tuple[str, str], tuple[str, str]] = {}
    provenance: dict[tuple[str, str], str] = {}
    stats: Counter = Counter()
    for key in sorted(unresolved):
        dll, name = key
        raw = forwarded.get(key)
        if not raw:
            continue
        module, dot, forwarded_name = raw.rpartition('.')
        if not dot or forwarded_name != name:
            continue
        contract = module.lower()
        if not contract.endswith('.dll'):
            contract += '.dll'
        if not is_api_set_contract(contract):
            continue
        # This function is truly declared as a forwarder in the source DLL.
        stats['unresolved contract forwarders inspected'] += 1
        stub = disk_stubs.get((contract, name))
        if stub:
            stub_module, _, stub_name = stub.rpartition('.')
            stub_dll = stub_module.lower()
            if not stub_dll.endswith('.dll'):
                stub_dll += '.dll'
            if stub_name != name or is_api_set_contract(stub_dll) or stub_dll == dll:
                stats['stub target is not same-name physical code'] += 1
                continue
            if name not in exports.get(stub_dll, set()):
                stats['stub destination lacks executable export'] += 1
                continue
            found[key] = (stub_dll, name)
            provenance[key] = f'disk API-set stub {contract} -> {stub_dll} (not loader verified)'
            stats['stub-linked candidates'] += 1
            continue
        candidates = sorted(d for d, symbols in exports.items()
                            if d != dll and not is_api_set_contract(d) and name in symbols)
        if len(candidates) == 1:
            found[key] = (candidates[0], name)
            provenance[key] = 'unique same-name executable export (not loader verified)'
            stats['unique-name candidates'] += 1
        else:
            stats['no candidate' if not candidates else 'ambiguous candidates'] += 1
    return found, provenance, stats


# --- Runtime-observed forwarders (exact function, no inferred contract host) ---
# The source DLL can forward to a virtual API-set for which the copied .apiset
# schema has no usable host. A GetProcAddress probe on the golden guest can
# establish the code address for this *particular* function. These observations
# are deliberately not translated into universal API-set contract mappings.

def load_guest_runtime_forwarders(
    path: Path,
    guest_root: Path,
    arch: str,
    guest_exports: dict[str, set[str]],
    guest_forwarders: dict[tuple[str, str], str],
    known_forwarders: dict[tuple[str, str], tuple[str, str]],
) -> tuple[dict[tuple[str, str], tuple[str, str]], Counter, list[str]]:
    """Verify an exact, same-address Win32 loader observation against PE copies.

    The accompanying PowerShell helper probes GetProcAddress in the same
    process for the forwarding DLL and the returned physical DLL. Its results
    are evidence for individual (source DLL, API) pairs, not proof that every
    function in an API-set contract uses the same host.

    SHA-256 hashes bind the observations to copied DLLs from the probed guest.
    All failures are fail-closed; no module is guessed from SDK metadata.
    """
    doc = json.loads(path.read_text(encoding='utf-8-sig'))
    if not isinstance(doc, dict) or doc.get('format') != 1:
        raise ValueError('runtime forwarders JSON must be format 1')
    if doc.get('architecture') != arch:
        raise ValueError('runtime forwarders architecture does not match --arch')
    if doc.get('method') != 'GetProcAddress:same-address':
        raise ValueError('unsupported runtime forwarder observation method')
    entries = doc.get('resolutions')
    if not isinstance(entries, list) or len(entries) > 10000:
        raise ValueError('runtime forwarders resolutions must be an array (max 10000)')
    pattern_dll = re.compile(r'[a-z0-9_.-]+\.dll')
    pattern_api = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')
    pattern_hash = re.compile(r'[0-9a-f]{64}')
    paths: dict[str, Path | None] = {}
    requested_names = set()
    for entry in entries:
        if isinstance(entry, dict):
            for field in ('source_dll', 'target_dll'):
                val = entry.get(field)
                if isinstance(val, str):
                    requested_names.add(val.lower())
    for item in guest_root.rglob('*'):
        if not item.is_file():
            continue
        key = item.name.lower()
        if key in requested_names:
            if key in paths:
                # A duplicate basename is ambiguous even if one file happens
                # to match the hash; the PE scanner also excludes duplicates.
                paths[key] = None
            else:
                paths[key] = item
    hashes: dict[str, str] = {}
    for dll, file in paths.items():
        if file is not None:
            hashes[dll] = hashlib.sha256(file.read_bytes()).hexdigest()
    found: dict[tuple[str, str], tuple[str, str]] = {}
    conflicts: set[tuple[str, str]] = set()
    reasons: Counter = Counter()
    details: list[str] = []
    for i, entry in enumerate(entries, 1):
        if not isinstance(entry, dict):
            reasons['invalid evidence entry'] += 1
            continue
        source, target = entry.get('source_dll'), entry.get('target_dll')
        name, target_name = entry.get('name'), entry.get('target_name')
        src_hash, dst_hash = entry.get('source_sha256'), entry.get('target_sha256')
        if not (isinstance(source, str) and isinstance(target, str)
                and isinstance(name, str) and isinstance(target_name, str)
                and isinstance(src_hash, str) and isinstance(dst_hash, str)):
            reasons['invalid evidence entry'] += 1
            continue
        source, target = source.lower(), target.lower()
        src_hash, dst_hash = src_hash.lower(), dst_hash.lower()
        if (not pattern_dll.fullmatch(source) or not pattern_dll.fullmatch(target)
                or is_api_set_contract(source) or is_api_set_contract(target)
                or source == target or not pattern_api.fullmatch(name)
                or target_name != name or not pattern_hash.fullmatch(src_hash)
                or not pattern_hash.fullmatch(dst_hash)
                or entry.get('same_address') is not True):
            reasons['invalid or non-identical target'] += 1
            continue
        key = source, name
        endpoint = target, name
        if source not in guest_exports or target not in guest_exports:
            reasons['source/target guest DLL not supplied'] += 1
            continue
        if (hashes.get(source) != src_hash or hashes.get(target) != dst_hash):
            reasons['guest DLL hash mismatch'] += 1
            details.append(f'{source},{name}: copied PE hashes differ from runtime probe')
            continue
        # Only recover an actual PE forwarder to an unresolved API-set, not a
        # same-named symbol on some unrelated host. Other forwarder chains are
        # already handled by the PE parser and must not be overridden.
        raw = guest_forwarders.get(key)
        module = raw.rpartition('.')[0].lower() if raw else ''
        if not module.endswith('.dll'):
            module += '.dll'
        if (not raw or not is_api_set_contract(module)
                or name in guest_exports.get(source, set())
                or name not in guest_exports[target]):
            reasons['no matching API-set PE forwarder/executable target'] += 1
            continue
        if key in known_forwarders:
            if known_forwarders[key] == endpoint:
                reasons['already verified by guest schema'] += 1
            else:
                reasons['conflicts with resolved guest schema'] += 1
            continue
        if key in conflicts:
            reasons['conflicting runtime observations'] += 1
            continue
        if key in found and found[key] != endpoint:
            found.pop(key)
            conflicts.add(key)
            reasons['conflicting runtime observations'] += 1
            continue
        found[key] = endpoint
    reasons['runtime forwarders accepted'] = len(found)
    return found, reasons, details


def physical_import_owners(imported_owners: dict[str, set[str]],
                           guest_host_map: dict[str, str],
                           guest_exports: dict[str, set[str]] | None = None
                           ) -> tuple[dict[str, set[str]], dict[str, int], list[str]]:
    """Keep actual DLL targets; resolve contracts only through guest mappings.

    Import-library records do not confirm exports in the guest. A physical DLL
    name merely supplies plausible DLL ownership for legacy retention.
    """
    guest_exports = guest_exports or {}
    physical: dict[str, set[str]] = {}
    unresolved: dict[str, set[str]] = {}
    mapped_contracts = 0
    directly_verified_crt = 0
    for symbol, owners in imported_owners.items():
        for owner in owners:
            if is_api_set_contract(owner):
                host = guest_host_map.get(owner.lower())
                if host and (host not in guest_exports
                             or symbol in guest_exports[host]):
                    physical.setdefault(symbol, set()).add(host)
                    mapped_contracts += 1
                    # V12 counted only the fallback path, giving a misleading
                    # zero when the schema correctly mapped CRT -> ucrtbase.
                    if (owner.lower().startswith('api-ms-win-crt-')
                            and host == 'ucrtbase.dll'
                            and symbol in guest_exports.get(host, set())):
                        directly_verified_crt += 1
                elif (owner.lower().startswith('api-ms-win-crt-')
                      and symbol in guest_exports.get('ucrtbase.dll', set())):
                    # This is NOT an inferred API-set schema mapping. The actual
                    # guest ucrtbase exports executable code at this symbol, so
                    # it can be hooked there independently of contract routing.
                    physical.setdefault(symbol, set()).add('ucrtbase.dll')
                    directly_verified_crt += 1
                else:
                    unresolved.setdefault(symbol, set()).add(owner)
            else:
                if owner not in guest_exports or symbol in guest_exports[owner]:
                    physical.setdefault(symbol, set()).add(owner)
    only_contracts = sorted(set(unresolved) - set(physical))
    counts = {
        "functions_with_physical_dll": len(physical),
        "functions_only_unmapped_contracts": len(only_contracts),
        "contract_records_mapped": mapped_contracts,
        "crt_symbols_with_verified_guest_code": directly_verified_crt,
    }
    sample = [f"{name}: {', '.join(sorted(unresolved[name]))}"
              for name in only_contracts[:8]]
    return physical, counts, sample


def _xwin_include_dirs(root: Path) -> list[Path]:
    """xwin's default splat layout, not the optional winsysroot layout."""
    dirs = [root / "crt/include", root / "sdk/include/um",
            root / "sdk/include/shared", root / "sdk/include/ucrt",
            root / "sdk/include/winrt"]
    present = [d for d in dirs if d.is_dir()]
    if not (root / "sdk/include/um").is_dir():
        raise ValueError("--xwin requires the standard xwin splat layout "
                         "(sdk/include/um). Re-run xwin without --use-winsysroot-style.")
    return present


def _xwin_candidate_headers(root: Path, missing: set[str], limit: int) -> list[Path]:
    """Find specific headers mentioning missing function names; bounded work."""
    if not missing or limit <= 0:
        return []
    regex = re.compile(rb"\b(?:" + b"|".join(re.escape(n.encode()) for n in sorted(missing,
                         key=len, reverse=True)) + rb")\s*\(")
    counts: list[tuple[int, int, Path]] = []
    for base in (root / "sdk/include/um", root / "sdk/include/shared",
                 root / "sdk/include/ucrt", root / "crt/include"):
        if not base.is_dir():
            continue
        for path in base.rglob("*.h"):
            try:
                if path.stat().st_size > 3_000_000:
                    continue
                buf = path.read_bytes()
            except OSError:
                continue
            # C++ AMP is an implementation header that matches generic
            # math names, not the public C prototypes we are looking for.
            if path.name.lower().startswith(('amp_', 'atl', 'cxx')):
                continue
            matches = set(regex.findall(buf))
            # `findall()` returns only a matched span. Use a match count as a
            # ranking heuristic; AST parsing still validates every prototype.
            if matches:
                counts.append((len(matches), -len(path.parts), path))
    counts.sort(key=lambda t: (-t[0], -t[1], str(t[2])))
    return [path for _, _, path in counts[:limit]]


def load_xwin_sdk(root: Path, needed: set[str], arch: str,
                  libclang: Path | None = None,
                  header_limit: int = 24,
                  extra_headers: list[str] | None = None,
                  ) -> tuple[dict[str, dict], list[str]]:
    """Extract actual declaration parameter names from Microsoft SDK headers.

    The SDK does not encode a reliable physical DLL/export ownership. The
    caller must join these names to existing Speakeasy/guest-profile evidence.
    """
    # Resolve --xwin while we still have the user's working directory.
    # Its paths will later be opened from a libclang synthetic TU in /tmp.
    root = root.expanduser().resolve(strict=True)
    include_dirs = _xwin_include_dirs(root)
    clang = _LibClang(libclang)
    log: list[str] = [f"libclang: {clang.path}"]
    found: dict[str, dict] = {}
    rejects: set[str] = set()
    # windows.h covers most Win32 functions; find targeted supplemental headers
    # rather than compiling thousands of SDK headers blindly.
    work: list[Path] = []
    windows_h = root / "sdk/include/um/Windows.h"
    if not windows_h.is_file():
        windows_h = root / "sdk/include/um/windows.h"
    if windows_h.is_file():
        work.append(windows_h)
    work += _xwin_candidate_headers(root, needed, header_limit)
    for hdr in (extra_headers or []):
        file = Path(hdr).expanduser()
        if file.is_file():
            work.append(file.resolve(strict=True))
        else:
            matches = [base / hdr for base in include_dirs if (base / hdr).is_file()]
            if not matches:
                raise ValueError(f"xwin header not found: {hdr}")
            work.append(matches[0])
    # Deduplicate using canonical paths (avoids mixed-case/symlink aliases).
    work = list(dict.fromkeys(p.resolve(strict=True) for p in work))
    attempted = 0
    for index, header in enumerate(work, 1):
        remaining = needed - found.keys() - rejects
        if not remaining:
            break
        attempted += 1
        records, warnings = clang.parse([header], include_dirs, remaining, arch)
        for warning in warnings:
            log.append(warning)
        for name, sig in records.items():
            # Preserve where the declaration came from. This is signature
            # provenance, NOT evidence of the function's exporting DLL.
            sig = dict(sig)
            declared_at = sig.pop('declaration_file', None)
            # Prefer the *real* declaration header recorded by libclang.
            # If an included CRT header is reached through Windows.h,
            # calling it sdk/include/um/Windows.h hides CRT provenance.
            if declared_at:
                actual = Path(declared_at).resolve()
                sig['sdk_header'] = (actual.relative_to(root).as_posix()
                                     if actual.is_relative_to(root) else actual.as_posix())
            else:
                sig['sdk_header'] = (header.relative_to(root).as_posix()
                                     if header.is_relative_to(root) else header.name)
            if name in found and {k:v for k,v in sig.items() if k != 'sdk_header'} != {k:v for k,v in found[name].items() if k != 'sdk_header'}:
                rejects.add(name)
                del found[name]
                log.append(f"{name}: conflicting SDK prototypes; discarded")
            elif name not in rejects:
                found[name] = sig
    log.append(f"SDK headers attempted: {attempted}; requested {len(needed)}; extracted {len(found)}")
    origins = Counter('CRT headers' if sig.get('sdk_header', '').startswith(
                      ('crt/include/', 'sdk/include/ucrt/')) else 'SDK headers'
                      for sig in found.values())
    if found:
        log.append('  declaration origins: ' + ', '.join(
            f'{key}={count}' for key, count in sorted(origins.items())))
    return found, log


def merge_xwin_signatures(xwin: dict[str, dict],
                          by_name: dict[str, tuple[str, str]],
                          statuses: dict[str, str],
                          hints: dict[str, str],
                          profiles: dict[str, set[str]],
                          retained: Path | None,
                          arch: str,
                          imported_owners: dict[str, set[str]] | None = None,
                          guest_exports: dict[str, set[str]] | None = None,
                          ) -> tuple[dict[str, dict], list[str]]:
    """Fill missing signatures; do not infer DLLs from header names."""
    log = []
    chosen = {}
    imported_owners = imported_owners or {}
    guest_exports = guest_exports or {}
    # Old hook file may supply the specific DLL identity but not correct args.
    legacy = {}
    if retained and retained.is_file():
        for line in retained.read_text(errors="replace").splitlines():
            m = _LEGACY_LINE.fullmatch(line.strip())
            if m:
                legacy.setdefault(m['fn'], set()).add(m['dll'].lower())
    for name, signature in sorted(xwin.items()):
        if name in by_name and by_name[name][1]:
            continue
        if name in statuses and "zero parameters (verified)" in statuses[name]:
            continue
        args, reason = signature_arguments(signature, arch)
        if not args:
            continue
        if name in by_name:
            dll = by_name[name][0]
            origin = "Speakeasy DLL"
        elif (hint := hints.get(name) or (
            hints.get(name[:-1]) if name.endswith(("A", "W")) else None)):
            if hint in KERNEL_MODULES:
                continue
            dll = hint.removesuffix('.dll') + '.dll'
            origin = "capa DLL hint (unverified)"
        elif (signature.get('sdk_header', '').startswith(('crt/include/', 'sdk/include/ucrt/'))
              and (name.startswith('_') or name in {n for n in legacy if any(d in CRT_DLLS for d in legacy[n])})):
            # CRT declarations establish names/arity, not a physical export.
            # If old hooks named both CRTs, keep both for the hook builder;
            # use ucrtbase as the canonical signature owner in by_name.
            owned = legacy.get(name, set()) & set(CRT_DLLS)
            dll = 'ucrtbase.dll' if 'ucrtbase.dll' in owned or not owned else 'msvcrt.dll'
            origin = 'xwin CRT header (DLL export UNVERIFIED)'
        elif (guest_matches := {d for d in legacy.get(name, set())
                                if name in guest_exports.get(d, set())}):
            if len(guest_matches) != 1:
                log.append(f"{name}: multiple legacy DLLs with executable guest exports")
                continue
            dll = next(iter(guest_matches))
            origin = "verified guest executable export + legacy DLL"
        elif (sdk_matches := (imported_owners.get(name, set()) & legacy.get(name, set()))):
            # Respect the user's exact old DLL, not an unrelated module.
            if len(sdk_matches) != 1:
                log.append(f"{name}: multiple matching legacy SDK import DLLs; cannot choose")
                continue
            dll = next(iter(sdk_matches))
            origin = "xwin import library + legacy DLL (guest export UNVERIFIED)"
        elif len(imported_owners.get(name, ())) == 1:
            dll = next(iter(imported_owners[name]))
            origin = "xwin import library (guest export UNVERIFIED)"
        elif len(legacy.get(name, ())) == 1:
            dll = next(iter(legacy[name]))
            origin = "legacy hook DLL (unverified)"
        else:
            # A profile could contain a same-named private routine. Do not
            # select e.g. mscorwks.dll as an Advapi32 API by coincidence.
            source = signature.get('sdk_header', 'unknown SDK header')
            log.append(f"{name}: named parameters from {source}, but no reliable DLL ownership")
            continue
        if is_api_set_contract(dll):
            log.append(f"{name}: API-set contract cannot be hooked as a DLL: {dll}")
            continue
        if dll in guest_exports and name not in guest_exports[dll]:
            log.append(f"{name}: {dll} exists in guest but has no executable named export")
            continue
        if name in guest_exports.get(dll, set()):
            origin += "; executable guest export VERIFIED"
        by_name[name] = (dll, args)
        statuses[name] = "xwin SDK named parameters; " + origin
        chosen[name] = {"dll": dll.removesuffix('.dll'),
                        "params": signature['params'],
                        "ret": signature['ret'], "conv": signature['conv'],
                        "arch": signature['arch']}
        log.append(f"  {name}: {len(signature['params'])} named parameters; {origin}")
    log.append(f"xwin augmented signatures: {len(chosen)}")
    return chosen, log


def resolve_windows(

    names: set[str], hints: dict[str, str],

    by_name: dict[str, tuple[str, str]],

    profiles: dict[str, set[str]] | None = None,

) -> tuple[dict[tuple[str, str], tuple[str, str]], list[str], list[str]]:

    """capa's bare names -> `{(dll, export): (provenance, args)}`.

    Also returns what could not be resolved, and what was REDIRECTED to a

    different DLL than its Speakeasy declaration -- both reported, because DRAKVUF

    reports neither.

    Provenance is recorded per line because the last rung is a documentation

    hint rather than a verified export, and a reader must be able to tell which

    is which without re-deriving it.

    """

    profiles = profiles or {}

    lines: dict[tuple[str, str], tuple[str, str]] = {}

    unresolved: list[str] = []

    redirected: list[str] = []

    for name in sorted(names):

        found = False
        if name.startswith(KERNEL_ONLY_PREFIXES):
            unresolved.append(f"{name} (kernel-only; cannot hook from a user DLL)")
            continue

        # 1 and 2: Speakeasy metadata, exact then A/W. DLLs are declarations;

        # A/W entries are separate source declarations, not synthesised here,
        # and the argument names come from the generated `params` records.

        for candidate in (name, name + "A", name + "W"):

            entry = by_name.get(candidate)

            if not entry:

                continue

            dll, args = entry

            if dll.rsplit(".", 1)[0] in KERNEL_MODULES or is_api_set_contract(dll):

                continue

            prov = "speakeasy"

            # **Prefer the DLL that actually holds the code.** On Windows 10

            # and 11 kernel32 forwards a great many APIs into kernelbase: this

            # guest (Win11 23H2) has no `OpenProcess` in `kernel32.json` while

            # its `kernelbase.json` does. win32metadata names the DOCUMENTED dll,

            # which for a forwarder is not where the function body is, and

            # apimon hooks a symbol it finds in a DLL's own export table.

            #

            # Only ever redirects when a profile for the named DLL exists AND

            # lacks the symbol AND another profile has it -- so a DLL we have no

            # profile for is left exactly as metadata says.

            stem = dll.rsplit(".", 1)[0]

            if stem in profiles and candidate not in profiles[stem]:

                better = [d for d, syms in profiles.items()
                          if candidate in syms and d in
                          ({"kernelbase"} if stem == "kernel32" else set())]

                if better:

                    # Deterministic, and the forwarders' real home first. A

                    # symbol several profiles hold went to whichever one the

                    # directory listed first: GetThreadContext came out in

                    # clr.dll on one run and in kernelbase on the next, and

                    # clr's is a private copy apimon never resolves (2026-11-04).

                    better.sort(key=lambda d: (d != "kernelbase", d))

                    dll = f"{better[0]}.dll"

                    prov = f"speakeasy, redirected to {dll} (profile)"

                    redirected.append(f"{candidate}: {stem}.dll -> {dll}")

            lines[(dll, candidate)] = (prov, args)

            found = True

        if found:

            continue

        # 3: psapi: Speakeasy includes K32-prefixed declarations.

        # because that is where they are implemented -- but `psapi.dll` exports

        # the un-prefixed name as a wrapper, and Microsoft documents it:

        # "If PSAPI_VERSION is 1, this function is defined as EnumProcesses ...

        # and exported in Psapi.lib and Psapi.dll as a wrapper that calls

        # K32EnumProcesses" (learn.microsoft.com, psapi/nf-psapi-enumprocesses).

        #

        # **The wrapper is the one worth hooking**, not the K32 implementation:

        # apimon reports the hooked symbol's own name, so a hook on

        # `K32EnumProcesses` emits a Method no capa rule looks for, while a hook

        # on `psapi.dll,EnumProcesses` emits exactly the documented name the

        # rules use. A caller compiled with PSAPI_VERSION=2 calls into kernel32

        # directly and is missed -- recorded here rather than papered over.

        # A/W applies here too: the kernel32 implementation of a string-taking

        # psapi call is `K32GetModuleFileNameExW`, and psapi.dll wraps it as

        # `GetModuleFileNameExW`.

        psapi = [f"{name}{s}" for s in ("", "A", "W") if f"K32{name}{s}" in by_name]

        if psapi:

            for export in psapi:

                # Args from the K32 implementation: psapi.dll's wrapper has the

                # same signature, which is what "wrapper that calls

                # K32EnumProcesses" means.

                _, args = by_name[f"K32{export}"]

                lines[("psapi.dll", export)] = (

                    "speakeasy (psapi K32 wrapper)", args)

            continue

        # 4: phnt natives are resolved by the same Speakeasy lookup above.
        # phnt entries are restricted to user-mode ntdll families when loaded.

        # 5: capa-rules' own module prefix. Documentation, so it is marked.

        hint = hints.get(name)

        if hint and hint not in KERNEL_MODULES and not is_api_set_contract(hint):

            lines[(f"{hint}.dll", name)] = ("capa-hint (UNVERIFIED export)", "")

            continue

        # 6: nothing. Reported, because DRAKVUF never will.

        unresolved.append(name)

    return lines, unresolved, redirected

# Profiles for things that are not user-mode DLLs, so a symbol found only in

# one of these is not evidence that apimon can hook it.

_NON_DLL_PROFILES = frozenset({"windows", "win32k", "tcpip", "ndis", "netio",

                               "ci", "fltmgr", "fwpkclnt", "hal", "services",

                               "android", "linux", "wow", "kernel32wow"})

def load_profiles(profiles_dir: Path) -> dict[str, set[str]]:

    """`{dll stem: symbol names}` from the volatility3 profiles in `profiles/`.

    **This is ground truth for the actual golden image**, where win32metadata is

    the SDK's documented view. The two disagree in a way that matters: modern

    kernel32 forwards a great many APIs into kernelbase, so `kernel32.json` has

    no `OpenProcess` while `kernelbase.json` does, and apimon resolves a symbol

    in the export table of the DLL it is told to look in.

    Only user-mode DLL profiles are returned. `windows.json` is the kernel,

    `win32k`/`tcpip`/`ndis`/`netio`/`ci`/`fltmgr`/`fwpkclnt`/`hal` are drivers,

    `services` is an exe, and `wow`/`kernel32wow` are the 32-bit-on-64 path --

    none is a DLL whose exports apimon walks in a normal process.

    Absent or unreadable profiles simply yield nothing: a fresh checkout has

    none (they are not git-tracked), and the generator must still run there.

    """

    out: dict[str, set[str]] = {}

    if not profiles_dir.is_dir():

        return out

    for path in sorted(profiles_dir.glob("*.json")):

        stem = path.stem

        if stem in _NON_DLL_PROFILES:

            continue

        try:

            data = json.loads(path.read_text())

        except Exception:

            continue

        symbols = data.get("symbols")

        if isinstance(symbols, dict) and symbols:

            out[stem] = set(symbols)

    return out

