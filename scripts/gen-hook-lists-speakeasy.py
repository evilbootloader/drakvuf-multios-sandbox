#!/usr/bin/env python3
"""Generate Windows DRAKVUF apimon and Linux libmon hook lists from capa-rules.

Windows: load Speakeasy's generated signature databases (not raw win32json):
  - win32json_signatures.json.gz: documented APIs
  - phnt_signatures.json.gz: ntdll native APIs

Both have format=2, a `functions` mapping, and each parameter is
[name, type_code, flags, optional_buffer_size]. The generated Windows hooks
preserve parameter names as Name:apimon_type, so apimon logs named arguments.

The DLL recorded in Speakeasy is a declaration, not guaranteed to be the
physical export on the target guest. The optional xwin libclang fallback
preincludes Windows.h before dependent SDK headers, sets Windows architecture
macros, and records the actual declaration location (not the umbrella
header) so CRT names are attributed correctly without treating headers
as proof of DLL exports. --xwin-import-libs optionally reads COFF short
import records to cross-check DLL imports but cannot verify guest exports. Offline mounted Windows images can be inspected via --guest-windows-root;
optional --offline-unique-forwarders is heuristic and NOT loader verified.
V16 can also relocate missing legacy exports using independent matching SDK
COFF import records and physically verified guest executable exports.
V17 additionally transfers reviewed prototype *names* onto legacy printer types
only when there is an exact arity match and trustworthy same-API evidence;
this never manufactures argument slots or silently replaces custom printers.
V18 corrects a small reviewed set of incorrectly copied Win32 API prototypes
with documented argument arity; all other legacy printers remain untouched.
Optional Volatility profiles redirect
exports when a different user-mode DLL holds the symbol.

Usage:
  python scripts/gen-hook-lists.py --rules capa-rules --speakeasy speakeasy --report
  python scripts/gen-hook-lists.py --rules capa-rules --speakeasy speakeasy --windows-only
  python scripts/gen-hook-lists.py ... --check

Speakeasy's .json.gz databases are generated by:
  python scripts/gen_win32_signatures.py
  python scripts/gen_phnt_signatures.py

This generator preserves lines above the BEGIN GENERATED marker in both
hook files. Run it again when capa-rules or Speakeasy signatures change.
"""

