def repair_reviewed_win32_abi(
    dll: str, name: str, args: str,
) -> tuple[str, str]:
    """Correct documented Win32 arity and invalid legacy 'void' printers.

    Same-size, type-only legacy entries keep every original printer and only
    gain parameter names. An incompatible positional list is replaced with a
    separately reviewed exact-symbol prototype; no function-name aliases are
    guessed, and no kernel/native API signatures are applied to Win32 exports.
    """
    expected = reviewed_win32_abi(dll, name)
    if expected is None:
        return args, ""
    old = args.split(",") if args else []
    if len(old) != len(expected) or any(
        part.partition(":")[2].lower() == "void" if ":" in part
        else part.lower() == "void" for part in old
    ):
        return ",".join(expected), (
            f"reviewed Win32 ABI correction: {name} old={len(old)} "
            f"documented={len(expected)} argument slots"
        )
    if old and all(":" not in item for item in old):
        names = [item.partition(":")[0] for item in expected]
        return ",".join(f"{param}:{typ}" for param, typ in zip(names, old)), (
            "reviewed Win32 ABI labels; original printer types preserved"
        )
    return args, ""



def add_reviewed_exact_legacy_labels(
    dll: str, name: str, args: str,
    guest_exports: dict[str, set[str]],
) -> tuple[str, str]:
    """Apply reviewed labels, never new argument slots or printer types.

    In particular, an import library or PDB profile is insufficient: the
    exact physical guest DLL must contain the corresponding executable export.
    Existing names must agree positionally with the reviewed prototype; a
    mismatch is rejected instead of overwriting the operator's labels.
    """
    dll = dll.lower()
    names = REVIEWED_EXACT_LEGACY_LABELS.get((dll, name))
    if names is None or name not in guest_exports.get(dll, set()):
        return args, ""
    fields = args.split(",") if args else []
    if len(fields) != len(names):
        return args, ""
    if any(not field or (field.partition(":")[2] if ":" in field else field).lower() == "void"
           for field in fields):
        return args, ""
    if any(":" in field and field.partition(":")[0].lower() != reviewed.lower()
           for field, reviewed in zip(fields, names)):
        return args, ""
    labelled = ",".join(
        field if ":" in field else f"{reviewed}:{field}"
        for field, reviewed in zip(fields, names)
    )
    if labelled == args:
        return args, ""
    return labelled, "reviewed exact-DLL parameter labels; types and arity preserved"


def repair_reviewed_generated_scalar_printers(
    entries: dict[tuple[str, str], tuple[str, str]],
) -> list[str]:
    """Correct one known Speakeasy scalar misclassification, not pointers.

    The reviewed CreateThread ABI has a SIZE_T dwStackSize (scalar). An
    affected win32json signature marks this parameter as pointer `p`, which
    apimon_type translates to `lpvoid`. Correcting this single scalar avoids
    representing the stack size as an address. Other `lpvoid` parameters,
    notably output pointers, remain untouched: decoding them at entry could
    read data not yet populated by the called function.

    Only change *generated* rows with the six exact reviewed parameter names;
    the caller excludes hand-curated hooks. Do not touch DLL selection or
    argument count.
    """
    notes: list[str] = []
    for key, (provenance, arguments) in list(entries.items()):
        dll, name = key
        if dll.lower() not in ("kernel32.dll", "kernelbase.dll") or name != "CreateThread":
            continue
        expected = reviewed_win32_abi(dll, name)
        tokens = arguments.split(",") if arguments else []
        if expected is None or len(tokens) != len(expected):
            continue
        if any(":" not in token or token.partition(":")[0] != template.partition(":")[0]
               for token, template in zip(tokens, expected)):
            continue
        if tokens[1] != "dwStackSize:lpvoid":
            continue
        tokens[1] = "dwStackSize:size_t"
        entries[key] = (provenance, ",".join(tokens))
        notes.append(f"{dll},{name}: dwStackSize:lpvoid -> dwStackSize:size_t (reviewed SIZE_T scalar)")
    return notes


def reviewed_abi_audit(text: str) -> list[str]:
    """Check curated and generated hooks, but never change hand-curated rows."""
    issues: list[str] = []
    for line in text.splitlines():
        match = _LEGACY_LINE.fullmatch(line.strip())
        if not match:
            continue
        expected = reviewed_win32_abi(match["dll"], match["fn"])
        if expected is None:
            continue
        args = (match["args"] or "").split(",") if match["args"] else []
        if len(args) != len(expected) or any(
            (arg.partition(":")[2] if ":" in arg else arg).lower() == "void"
            for arg in args
        ):
            issues.append(
                f"{match['dll']},{match['fn']}: {len(args)} slots in file "
                f"vs {len(expected)} documented; check curated/legacy ABI"
            )
        elif match["fn"] == "CreateThread" and (
            (args[1].partition(":")[2] if ":" in args[1] else args[1]).lower()
            == "lpvoid"
        ):
            # Narrow: lpvoid may be correct for IN/OUT pointers, but never
            # for CreateThread's by-value SIZE_T dwStackSize.
            issues.append(
                f"{match['dll']},{match['fn']}: dwStackSize is SIZE_T (scalar), "
                "but its printer is lpvoid (pointer)"
            )
    return issues


_LEGACY_LINE = re.compile(
    r"^(?P<dll>[A-Za-z0-9_.-]+\.dll),(?P<fn>[A-Za-z_][A-Za-z0-9_]*),"
    r"(?P<action>log(?:\+stack)?)(?:,(?P<args>.*))?$",
    re.IGNORECASE,
)
_LEGACY_TOKEN = re.compile(r"^[A-Za-z_][A-Za-z0-9_*]*(?::[A-Za-z_][A-Za-z0-9_*]*)?$")




def named_legacy_argument_types(
    original_dll: str, target_dll: str, name: str, legacy_args: str,
    signatures: dict[str, tuple[str, str]],
    statuses: dict[str, str] | None = None,
    sdk_prototypes: dict[str, dict] | None = None,
    imported_owners: dict[str, set[str]] | None = None,
    guest_exports: dict[str, set[str]] | None = None,
    verified_relocation: bool = False,
    arch: str = "x64",
    allow_guest_export_sdk_names: bool = False,
) -> tuple[str, str]:
    """Add *names*, not arguments or types, to an old apimon line.

    Old hook files intentionally use specialized printers such as ``hkey`` and
    ``lpcolestr``. Speakeasy/libclang may know names but use generic pointer
    printers. Their names can be transferred when the ABI slot count agrees,
    while preserving every old printer and the function's exact symbol name.

    The destination has to be the same declared module, the prior declared
    module of a verified relocation, or a verified export with a matching SDK
    import record. An unrelated DLL exporting an identically named private
    routine is not enough to make the transfer.
    """
    statuses = statuses or {}
    sdk_prototypes = sdk_prototypes or {}
    imported_owners = imported_owners or {}
    guest_exports = guest_exports or {}
    if not legacy_args:
        return legacy_args, "no argument slots declared"
    types = legacy_args.split(",")
    if all(":" in token for token in types):
        return legacy_args, "already has names"
    if len(types) == 1 and types[0].lower() == "void":
        # The old DRAKVUF list sometimes used `void` as a placeholder for a
        # *zero*-argument API, but it can be wrongly decoded as one argument.
        # Remove it only if an independent source explicitly verifies arity 0.
        sig = signatures.get(name)
        if (sig and not sig[1] and "zero parameters (verified)" in statuses.get(name, "")
                and (sig[0].lower() in (target_dll, original_dll)
                     or (name in guest_exports.get(target_dll, set())
                         and target_dll in imported_owners.get(name, set())))):
            return "", "verified zero-argument prototype: removed legacy void sentinel"
        sdk = sdk_prototypes.get(name)
        if (sdk and sdk.get("params") == []
                and name in guest_exports.get(target_dll, set())
                and target_dll in imported_owners.get(name, set())):
            return "", "verified zero-argument SDK prototype: removed legacy void sentinel"
        return legacy_args, "legacy void sentinel without matching verified zero-argument prototype"
    mixed = any(":" in token for token in types)
    if any((token.partition(":")[2] if ":" in token else token).lower() == "void"
           for token in types):
        return legacy_args, "legacy void token among argument slots (review required)"

    candidates: list[tuple[str, list[str]]] = []
    signature = signatures.get(name)
    if signature and signature[1]:
        owner, named_args = signature
        # A named signature for another DLL can be used if the old API was
        # relocated with independently corroborated executable export evidence.
        if (owner.lower() in (target_dll, original_dll) or verified_relocation):
            candidates.append(("Speakeasy/accepted SDK", named_args.split(",")))
    sdk = sdk_prototypes.get(name)
    if sdk:
        sdk_args, _ = signature_arguments(sdk, arch)
        target_has_code = name in guest_exports.get(target_dll, set())
        has_sdk_owner = target_dll in imported_owners.get(name, set())
        if sdk_args and target_has_code and has_sdk_owner:
            candidates.append(("xwin SDK prototype + verified guest import/export", sdk_args.split(",")))
        elif (sdk_args and target_has_code and allow_guest_export_sdk_names
              and (target_dll == original_dll or verified_relocation)):
            # No DLL ownership inference: just adopt independently declared
            # *parameter labels* for this exact executable export, with a
            # matching argument count. Retain ALL old printer types.
            candidates.append(("xwin SDK declaration + executable guest export "
                               "(owner not independently corroborated)", sdk_args.split(",")))

    for provenance, candidate in candidates:
        if len(candidate) != len(types):
            continue
        param_names = [p.partition(":")[0] for p in candidate]
        # Do not invent `Arg0` labels in lieu of actual declaration names.
        if (len(set(param_names)) != len(param_names) or
                any(not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", p)
                    or re.fullmatch(r"Arg[0-9]+", p) for p in param_names)):
            continue
        if mixed:
            # Never overwrite an existing label, even if the C declaration
            # uses a different spelling. Only complete a partial row if all
            # existing names agree case-insensitively with the prototype.
            if any((old.partition(":")[0].lower() != pname.lower())
                   for pname, old in zip(param_names, types) if ":" in old):
                continue
            result = ",".join(
                old if ":" in old else f"{pname}:{old}"
                for pname, old in zip(param_names, types))
        else:
            result = ",".join(f"{p}:{t}" for p, t in zip(param_names, types))
        return result, (
            f"names transferred from {provenance}; original types preserved")
    return legacy_args, "no safe named prototype with matching argument count"


def legacy_names_needing_sdk_rescan(previous: Path | None,
                                    by_name: dict[str, tuple[str, str]],
                                    sdk_records: dict[str, dict],
                                    arch: str = "x64") -> set[str]:
    """Prioritize real old type-only hooks rather than all capa API features.

    This is only about obtaining documented argument NAMES. We do not
    synthesize an argument count, change printer types, or trust a header
    declaration as evidence of a guest DLL export.
    """
    if previous is None or not previous.is_file():
        return set()
    wanted: set[str] = set()
    for line in previous.read_text(errors="replace").splitlines():
        m = _LEGACY_LINE.fullmatch(line.strip())
        if not m or not m["args"]:
            continue
        original = m["args"].split(",")
        if any((part.partition(":")[2] if ":" in part else part).lower() == "void"
               for part in original):
            continue
        if all(":" in part for part in original):
            continue
        name = m["fn"]
        sdk = sdk_records.get(name)
        if sdk:
            args, _ = signature_arguments(sdk, arch)
            if args and len(args.split(",")) == len(original):
                continue
        existing = by_name.get(name)
        if existing and existing[1]:
            # Only skip when a signature comes from the SAME original DLL:
            # an unrelated owner or wrong-arity prototype cannot fill labels.
            named = existing[1].split(",")
            real_labels = all(":" in part and not re.fullmatch(
                r"Arg[0-9]+", part.partition(":")[0]) for part in named)
            if (existing[0].lower() == m["dll"].lower() and
                    len(named) == len(original) and real_labels):
                continue
        wanted.add(name)
    return wanted


def remaining_argument_evidence(
    text: str, sdk_prototypes: dict[str, dict],
    signatures: dict[str, tuple[str, str]],
    imported_owners: dict[str, set[str]],
    guest_exports: dict[str, set[str]],
    arch: str = "x64",
) -> tuple[Counter, list[str]]:
    """Explain *why* an emitted type-only hook cannot safely gain SDK names.

    This is an audit only: neither owner, printer type nor arity is changed.
    It deliberately uses the emitted hook DLL, not any old source name, so
    the result can be cross-checked against the exact PE export corpus.
    """
    counts: Counter = Counter()
    details: list[str] = []
    for raw in text.splitlines():
        m = _LEGACY_LINE.fullmatch(raw.strip())
        if not m or not m['args']:
            continue  # zero/unknown arguments have a separate audit
        tokens = m['args'].split(',')
        if all(':' in t for t in tokens):
            continue
        dll, name = m['dll'].lower(), m['fn']
        values = [t.partition(':')[2] if ':' in t else t for t in tokens]
        if any(t.lower() == 'void' for t in values):
            why = 'void printer token: requires reviewed prototype'
        else:
            sdk = sdk_prototypes.get(name)
            if sdk is None:
                existing = signatures.get(name)
                if existing and existing[1] and len(existing[1].split(',')) == len(tokens):
                    why = ('named signature exists for ' + existing[0] +
                           ', but not accepted for this row')
                else:
                    why = 'no accepted SDK prototype with named arguments'
            else:
                rendered, _ = signature_arguments(sdk, arch)
                if not rendered:
                    why = 'SDK prototype has no safely printable argument layout'
                else:
                    parts = rendered.split(',')
                    if len(parts) != len(tokens):
                        why = (f'SDK argument-count mismatch: hook={len(tokens)}, '
                               f'prototype={len(parts)}')
                    elif any(':' in old and old.partition(':')[0].lower() !=
                             proposed.partition(':')[0].lower()
                             for old, proposed in zip(tokens, parts)):
                        why = 'existing parameter label disagrees with SDK prototype'
                    elif name not in guest_exports.get(dll, set()):
                        why = ('physical DLL executable export not verified' if
                               dll not in guest_exports else
                               'hook DLL has no executable named export')
                    elif dll not in imported_owners.get(name, set()):
                        why = ('matching SDK names + guest code export; '
                               'DLL import owner uncorroborated (opt-in available)')
                    else:
                        why = ('SDK names, arity, import owner and guest code agree; '
                               'check generated-vs-retained path')
        counts[why] += 1
        details.append(f'{dll},{name}: {why}')
    return counts, details


def void_argument_lines(text: str) -> list[str]:
    """Find legacy `void` printers which apimon could read as argument slots.

    No-op APIs correctly represented as `...,log` do not appear here. This
    gate covers standalone sentinels and void in a multi-argument list.
    """
    unsafe: list[str] = []
    for line in text.splitlines():
        m = _LEGACY_LINE.fullmatch(line.strip())
        if not m or not m['args']:
            continue
        tokens = m['args'].split(',')
        if any((token.partition(':')[2] if ':' in token else token).lower()
               == 'void' for token in tokens):
            unsafe.append(line.strip())
    return unsafe


def compact_legacy_header_errors(log: list[str], limit: int = 8) -> list[str]:
    """Distinguish per-header parse failures from successfully parsed TUs."""
    failures = [msg for msg in log if re.match(r'^[^:]+\.h: ', msg, re.I)]
    if not failures:
        return log
    names = {msg.split(':', 1)[0] for msg in failures}
    result = [msg for msg in log if msg not in failures]
    summary = (f'{len(names)} SDK header(s) skipped due to libclang errors; '
               'other headers remain usable (sample follows)')
    return [summary] + failures[:limit] + (
        [f'... {len(failures) - limit} additional compiler messages omitted']
        if len(failures) > limit else []) + result


def argument_audit_by_region(text: str) -> dict[str, Counter]:
    """Separate immutable hand-curated entries from regenerated entries."""
    curated, sep, generated = text.partition(BEGIN)
    result = {"hand-curated": argument_label_audit(curated)[0],
              "generated": argument_label_audit(generated if sep else "")[0]}
    return result


def argument_label_audit(text: str) -> tuple[Counter, list[str]]:
    """Audit all actual hook lines, not just the new capa-derived subset."""
    stats: Counter = Counter()
    unlabelled: list[str] = []
    for line in text.splitlines():
        match = _LEGACY_LINE.fullmatch(line.strip())
        if not match:
            continue
        fields = (match["args"] or "").split(",") if match["args"] else []
        if not fields:
            stats["no argument tokens (zero or unknown)"] += 1
        elif fields == ["void"]:
            stats["legacy void sentinel (review)"] += 1
            unlabelled.append(line.strip())
        elif all(":" in f for f in fields):
            stats["all argument slots named"] += 1
        else:
            stats["unnamed or mixed argument slots"] += 1
            unlabelled.append(line.strip())
    return stats, unlabelled


def retain_previous_hooks(
    previous: Path,
    lines: dict[tuple[str, str], tuple[str, str]],
    curated: set[tuple[str, str]],
    profiles: dict[str, set[str]],
    signatures: dict[str, tuple[str, str]],
    allow_unverified: bool = False,
    imported_owners: dict[str, set[str]] | None = None,
    guest_exports: dict[str, set[str]] | None = None,
    forwarded_targets: dict[tuple[str, str], tuple[str, str]] | None = None,
    unresolved_forwarders: dict[tuple[str, str], str] | None = None,
    offline_candidates: dict[tuple[str, str], tuple[str, str]] | None = None,
    offline_sources: dict[tuple[str, str], str] | None = None,
    signature_statuses: dict[str, str] | None = None,
    sdk_prototypes: dict[str, dict] | None = None,
    arch: str = "x64",
    name_legacy_arguments: bool = True,
    allow_guest_export_sdk_names: bool = False,
    repair_reviewed_abi: bool = True,
) -> tuple[dict[tuple[str, str], str], Counter, list[str]]:
    """Supplement capa-derived hooks from an older list, retaining old actions.

    Never equate a missing rule with an invalid hook. Conversely, a hook in an
    older list is not proof that the target DLL exports that symbol. The user
    must opt in to unverified entries where no DLL profile exists.

    No old entries overwrite curated or newly generated hooks. For an old DLL
    which *has* a profile but lacks the symbol, relocate to a profile-listed
    module if possible; otherwise do not silently preserve the stale DLL.
    """
    imported_owners = imported_owners or {}
    guest_exports = guest_exports or {}
    forwarded_targets = forwarded_targets or {}
    unresolved_forwarders = unresolved_forwarders or {}
    offline_candidates = offline_candidates or {}
    offline_sources = offline_sources or {}
    result: dict[tuple[str, str], str] = {}
    reasons: Counter = Counter()
    notes: list[str] = []
    text = previous.read_text(encoding="utf-8", errors="replace")
    for number, raw in enumerate(text.splitlines(), 1):
        value = raw.strip()
        if not value or value.startswith("#"):
            continue
        match = _LEGACY_LINE.fullmatch(value)
        if not match:
            reasons["unsupported legacy grammar"] += 1
            notes.append(f"line {number}: skipped unsupported syntax: {value[:150]}")
            continue
        dll = match["dll"].lower()
        name = match["fn"]
        action = match["action"]
        args = match["args"] or ""
        stem = dll.removesuffix(".dll")
        if is_api_set_contract(dll):
            reasons["excluded API-set contract (not a module)"] += 1
            notes.append(f"{dll},{name}: API-set contract is not a physical hook target")
            continue
        if (stem in KERNEL_MODULES or name.startswith(KERNEL_ONLY_PREFIXES)
                or name in NON_WINDOWS_CRT):
            reasons["excluded kernel-only / non-Windows"] += 1
            continue
        if args and not all(_LEGACY_TOKEN.fullmatch(token) for token in args.split(",")):
            sig = signatures.get(name)
            if sig and sig[1]:
                args = sig[1]
                reasons["replaced invalid legacy tokens with named signature"] += 1
            else:
                reasons["invalid legacy argument token"] += 1
                notes.append(f"line {number}: skipped invalid argument token: {dll},{name}")
                continue
        original_dll = dll
        original_key = (dll, name)
        if original_key in curated or original_key in lines or original_key in result:
            reasons["already present"] += 1
            continue

        verified_relocation = False
        if dll in guest_exports and name not in guest_exports[dll]:
            # Verified PE forwarders are stronger than same-name guesses.
            # Keeping the API name is essential for capa's api: features;
            # otherwise require a future explicit alias feature, not a silent
            # rename that makes the rule appear to match while it cannot.
            forwarded_to = forwarded_targets.get((dll, name))
            if forwarded_to is not None:
                new_dll, new_name = forwarded_to
                if new_name != name:
                    reasons["rejected, forwarder changes API name"] += 1
                    notes.append(f"{dll},{name}: forwarded to {new_dll},{new_name}; "
                                 "API name differs, not safe for capa")
                    continue
                notes.append(f"{dll},{name} -> {new_dll},{name} "
                             "(verified guest PE forwarder chain)")
                reasons["relocated, verified guest PE forwarder chain"] += 1
                dll = new_dll
                stem = dll.removesuffix('.dll')
                verified_relocation = True
            else:
                # A short COFF import record names a *physical* DLL and the
                # mounted guest proves that DLL actually exports executable
                # code under the same name. This is stronger than the offline
                # unique-name heuristic: it is two independent pieces of
                # evidence, not a guess based on duplicate symbol names.
                # Ignore source DLLs whose export is absent, and require an
                # unambiguous verified destination before relocating.
                import_code_dlls = sorted(
                    owner for owner in imported_owners.get(name, set())
                    if owner != dll and not is_api_set_contract(owner)
                    and name in guest_exports.get(owner, set())
                )
                if len(import_code_dlls) == 1:
                    target_dll = import_code_dlls[0]
                    notes.append(
                        f"{dll},{name} -> {target_dll},{name} "
                        "(guest executable export + SDK import-library owner; "
                        "not proof of original DLL's runtime routing)"
                    )
                    reasons["relocated, verified guest export + SDK import owner"] += 1
                    dll = target_dll
                    stem = dll.removesuffix('.dll')
                elif len(import_code_dlls) > 1:
                    reasons["rejected, ambiguous verified SDK import owners"] += 1
                    notes.append(f"{dll},{name}: multiple SDK import DLLs contain "
                                 f"verified code exports: {', '.join(import_code_dlls)}")
                    continue
                elif (dll, name) in offline_candidates:
                    new_dll, new_name = offline_candidates[(dll, name)]
                    if new_name != name or name not in guest_exports.get(new_dll, set()):
                        reasons["rejected unsafe offline forwarder candidate"] += 1
                        continue
                    notes.append(f"{dll},{name} -> {new_dll},{name} "
                                 f"(OFFLINE INFERENCE: {offline_sources.get((dll, name), 'code export candidate')})")
                    reasons["relocated, offline inference (NOT loader verified)"] += 1
                    dll = new_dll
                    stem = dll.removesuffix('.dll')
                elif (dll == "kernel32.dll"
                      and name in guest_exports.get("kernelbase.dll", set())):
                    notes.append(f"{dll},{name} -> kernelbase.dll,{name} (guest executable export)")
                    reasons["relocated, guest executable export VERIFIED"] += 1
                    dll = "kernelbase.dll"
                    stem = "kernelbase"
                else:
                    reasons["rejected, present guest DLL does not export executable function"] += 1
                    if note := unresolved_forwarders.get((dll, name)):
                        notes.append(f"{dll},{name}: PE forwarder {note}")
                    else:
                        notes.append(f"{dll},{name}: guest PE has no executable named export")
                    continue
        if name in guest_exports.get(dll, set()):
            reasons["retained, guest executable export VERIFIED"] += 1
        elif dll in imported_owners.get(name, set()):
            # A public SDK import library names the actual import DLL, so
            # absence from a PDB *symbol* profile is not evidence against it.
            # Still not proof that the specific guest build exports the API.
            reasons["retained, xwin SDK import DLL (guest UNVERIFIED)"] += 1
        elif stem in profiles:
            if name in profiles[stem]:
                reasons["retained, listed by target profile"] += 1
            else:
                alternatives = sorted(
                    (d for d, syms in profiles.items() if name in syms
                     and d == "kernelbase" and stem == "kernel32"),
                )
                if not alternatives:
                    reasons["rejected, profile does not list export"] += 1
                    notes.append(f"{dll},{name}: not found in available module profiles")
                    continue
                new_dll = alternatives[0] + ".dll"
                reasons["relocated, supported by profile"] += 1
                notes.append(f"{dll},{name} -> {new_dll},{name}")
                dll = new_dll
        else:
            if not allow_unverified:
                reasons["skipped, no profile for source DLL"] += 1
                continue
            reasons["retained without DLL verification (explicit override)"] += 1

        key = (dll, name)
        if key in curated or key in lines or key in result:
            reasons["already present at destination"] += 1
            continue
        sig = signatures.get(name)
        # Preserve the old specialty printer types and transfer names only
        # after matching the exact ABI arity. A verified target relocation
        # lets us accept the old DLL's prototype as the same API.
        if name_legacy_arguments and args:
            converted, detail = named_legacy_argument_types(
                original_dll, dll, name, args, signatures,
                statuses=signature_statuses, sdk_prototypes=sdk_prototypes,
                imported_owners=imported_owners, guest_exports=guest_exports,
                verified_relocation=(verified_relocation or (
                    dll != original_dll and name in guest_exports.get(dll, set())
                    and (dll in imported_owners.get(name, set()) or
                         (original_dll, name) in forwarded_targets))),
                arch=arch,
                allow_guest_export_sdk_names=allow_guest_export_sdk_names)
            if converted != args:
                args = converted
                reasons[detail] += 1
        # A source-equivalent named signature is still useful for previously
        # completely untyped legacy lines. Do not replace explicit old printer
        # types, especially when a signature is more generic.
        if not args and sig and sig[1] and sig[0].lower() == dll:
            args = sig[1]
            reasons["retained with Speakeasy names"] += 1
        if repair_reviewed_abi:
            corrected, explanation = repair_reviewed_win32_abi(dll, name, args)
            if corrected != args:
                args = corrected
                reasons["reviewed Win32 ABI repaired/labelled"] += 1
                notes.append(f"{dll},{name}: {explanation}")
        if name_legacy_arguments and args:
            reviewed, label_source = add_reviewed_exact_legacy_labels(
                dll, name, args, guest_exports)
            if reviewed != args:
                args = reviewed
                reasons[label_source] += 1
        result[key] = f"{dll},{name},{action}" + (f",{args}" if args else "")
    return result, reasons, notes

def hook_entries(text: str) -> set[tuple[str, str]]:
    """Active (DLL, API) keys; never count comments or blank lines."""
    entries: set[tuple[str, str]] = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(",", 3)
        if len(parts) >= 3 and parts[2] in ("log", "log+stack"):
            entries.add((parts[0].lower(), parts[1]))
    return entries


def compare_hooks(old_file: Path, generated_text: str) -> None:
    old = hook_entries(old_file.read_text(errors="replace"))
    new = hook_entries(generated_text)
    removed = sorted(old - new)
    added = sorted(new - old)
    print(f"\nHOOK COMPARISON: previous {len(old)}, generated {len(new)}; "
          f"removed {len(removed)}, added {len(added)}; net {len(new) - len(old):+d}")
    for label, items in (("REMOVED / RELOCATED", removed), ("ADDED / RELOCATED", added)):
        print(f"{label} ({len(items)}):")
        for dll, fn in items:
            counterpart = next((d for d, f in (new if label.startswith("REMOVED") else old)
                                if f == fn), None)
            note = f" (other DLL: {counterpart})" if counterpart else ""
            print(f"  {dll},{fn}{note}")


