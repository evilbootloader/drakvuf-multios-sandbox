"""What CAPE knows about an API that DRAKVUF does not say: its category, and
the names CAPE gives its arguments.

**Argument names.** CAPE's processing and signatures look arguments up by
the name capemon logs them under (`SubKey`, `CommandLine`, `FileName`), not
by the prototype's (`lpSubKey`, `lpCommandLine`, `ObjectAttributes`), which
is what DRAKVUF prints. `data/api_arguments.json` maps one to the other per
API, read out of capemon's hooks where a logged value is a hook parameter
as it stands; `cape_aliases` adds CAPE's name beside DRAKVUF's.

**Categories.** CAPE's monitor (capemon) tags each hooked API with a category -- `network`,
`filesystem`, `registry`, `process`, `crypto`, ... -- and signatures and the
web UI filter on it. DRAKVUF has no such tag, and its plugin is no stand-in:
apimon alone covers ws2_32 (network), advapi32 (registry, crypto, services)
and kernel32 (filesystem, process, synchronization). So the category comes
from the API's name:

1. `data/api_categories.json`, generated by `scripts/gen-cape-api-tables.py`
   from capemon itself, then the Cuckoo monitor, CAPEv2's logtbl, win32json
   namespaces, the DLL in hooks.txt and phnt's header -- the file names its
   sources and their revisions;
2. win32k's syscall families, which phnt does not declare;
3. `LINUX`, by hand: no Linux sandbox publishes a table, and falco's event
   classes cover a fraction of what libmon and the syscall plugin record;
4. the DRAKVUF plugin, last.

**No stdlib-external imports, and no relative ones:** the generator loads this
file by path for `canonical`, so that the table's keys and the lookups here
are normalised by one function.
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Dict

TABLE = Path(__file__).with_name("data") / "api_categories.json"
ARGUMENTS = Path(__file__).with_name("data") / "api_arguments.json"
OUTPUTS = Path(__file__).with_name("data") / "api_outputs.json"
# sandboxd/data/hooks.txt: what apimon was told to print for each argument.
HOOKS = Path(__file__).resolve().parents[3] / "data" / "hooks.txt"

# The hook-list types that make apimon read THROUGH the argument, at return
# (libusermode/utils.cpp::make_arg_printer). Any other type prints the
# argument itself, which for an output is the address of the caller's
# variable.
DEREFERENCING_TYPES = frozenset(("lpvoid*", "pulong", "pulonglong"))

# Outputs capemon's hooks do not show mechanically: DRAKVUF's own spelling
# of a parameter capemon logs under a computed name.
EXTRA_OUTPUTS = {
    "NtProtectVirtualMemory": ("RegionSize", "OldProtect", "OldAccessProtection"),
    "NtFreeVirtualMemory": ("RegionSize",),
    "NtCreateUserProcess": ("ProcessHandle", "ThreadHandle"),
}


def canonical(name: str) -> str:
    """The name under which an API is categorised: `Zw` read as `Nt` (the
    same system service), and a trailing ANSI/wide `A`/`W` dropped
    (`CreateFileW` -> `CreateFile`) -- only after a lowercase letter or a
    digit, so `NtCreateWnfStateName` or an all-caps name keeps its last
    letter."""
    if name.startswith("Zw") and len(name) > 2 and name[2].isupper():
        name = "Nt" + name[2:]
    if len(name) > 3 and name[-1] in "AW" and (name[-2].islower() or name[-2].isdigit()):
        name = name[:-1]
    return name


@lru_cache(maxsize=1)
def _table() -> Dict[str, str]:
    try:
        return json.loads(TABLE.read_text())["categories"]
    except FileNotFoundError:
        return {}


@lru_cache(maxsize=1)
def _arguments() -> Dict[str, Dict[str, str]]:
    try:
        return json.loads(ARGUMENTS.read_text())["arguments"]
    except FileNotFoundError:
        return {}


@lru_cache(maxsize=1)
def _outputs() -> Dict[str, frozenset]:
    try:
        table = json.loads(OUTPUTS.read_text())["outputs"]
    except FileNotFoundError:
        table = {}
    out = {api: set(names) for api, names in table.items()}
    for api, names in EXTRA_OUTPUTS.items():
        out.setdefault(api, set()).update(names)
    return {api: frozenset(names) for api, names in out.items()}


@lru_cache(maxsize=1)
def _hook_types() -> Dict[str, Dict[str, str]]:
    """`{canonical api: {argument: type}}` from hooks.txt."""
    out: Dict[str, Dict[str, str]] = {}
    try:
        lines = HOOKS.read_text().splitlines()
    except FileNotFoundError:
        return out
    for line in lines:
        if not line or line.startswith("#"):
            continue
        fields = line.strip().split(",")
        if len(fields) < 3:
            continue
        types = out.setdefault(canonical(fields[1]), {})
        for token in fields[2:]:
            name, sep, kind = token.partition(":")
            if sep:
                types[name] = kind
    return out


def settle_outputs(api: str, plugin: str, arguments: list, returned=()) -> list:
    """Rename every output argument whose value is NOT the output.

    capemon logs an output argument after the call, dereferenced: the
    handle that was opened, the base that was allocated. DRAKVUF's syscall
    plugin prints arguments at entry, so the same name carries the address
    of the caller's variable -- and a signature that reads `BaseAddress` and
    `RegionSize` from NtAllocateVirtualMemory builds a "region" out of two
    stack addresses (SteamSetup, 2026-11-10: twelve `unbacked_*` matches,
    malscore 9.0). Such an argument is renamed `<name>_ptr`: still in the
    record, under a name no signature asks for.

    Left alone: a value the sysret record supplied (`returned`, from a
    DRAKVUF that prints outputs at return), and an apimon argument whose
    hook-list type dereferences it -- apimon formats at return."""
    for arg in arguments:
        name = arg.get("name")
        if isinstance(name, str) and name.startswith("*"):
            # The syscall plugin's own mark for a pointer argument.
            arg["name"] = name = name[1:]
    names = _outputs().get(canonical(api))
    if not names:
        return arguments
    types = _hook_types().get(canonical(api), {}) if plugin == "apimon" else {}
    """
    for arg in arguments:
        name = arg.get("name")
        if name not in names or name in returned:
            continue
        if plugin == "apimon" and types.get(name) in DEREFERENCING_TYPES:
            continue
        if plugin in ("apimon", "syscall"):
            arg["name"] = f"{name}_ptr"
    """
    return arguments


# Where the API's own RETURN VALUE is what signatures read from an input
# argument. capemon does not hook these (it hooks the Nt* service under
# them), yet some thirty-five signatures list them and read `lpAddress` as
# the address that was allocated; as passed it is the address asked for,
# nearly always 0 -- a "region" from 0 that swallows a 32-bit image.
RETURNED_AS = {"VirtualAlloc": "lpAddress", "VirtualAllocEx": "lpAddress"}


def returned_as_argument(api: str, arguments: list, return_value) -> list:
    name = RETURNED_AS.get(api)
    if name is None:
        return arguments
    try:
        allocated = int(str(return_value), 16)
    except ValueError:
        allocated = 0
    for arg in arguments:
        if arg.get("name") == name:
            if allocated:
                arguments.append({"name": f"{name}_requested", "value": arg.get("value")})
                arg["value"] = return_value
            else:
                # The call failed: nothing was allocated at any address.
                arg["name"] = f"{name}_requested"
            break
    return arguments


def cape_aliases(api: str, arguments: list) -> list:
    """`arguments` (`{name, value}`), plus each one again under capemon's
    name for it where that differs and is not already there. Both stay: the
    prototype's name is what capa and hand-written handlers read, CAPE's
    what CAPE's signatures read."""
    names = _arguments().get(canonical(api))
    if not names:
        return arguments
    have = {a.get("name") for a in arguments}
    extra = []
    for a in arguments:
        cape = names.get(a.get("name"))
        if cape and cape not in have:
            have.add(cape)
            extra.append({"name": cape, "value": a.get("value")})
    return arguments + extra if extra else arguments


