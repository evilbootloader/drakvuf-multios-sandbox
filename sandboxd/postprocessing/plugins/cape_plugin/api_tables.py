# What a plugin's records are about when the API name says nothing.
PLUGIN_FALLBACK = {
    "regmon": "registry", "filetracer": "filesystem", "socketmon": "network",
    "unixsocketmon": "network", "procmon": "process", "cpuidmon": "system",
    "ptracemon": "process", "debugmon": "system", "ebpfmon": "system",
}


def category(api: str, plugin: str, linux: bool) -> str:
    if not api:
        return PLUGIN_FALLBACK.get(plugin, "misc")
    if linux:
        cat = LINUX.get(api)
        if cat:
            return cat
    else:
        cat = _table().get(canonical(api))
        if cat:
            return cat
        if api.startswith(WIN32K_PREFIXES):
            return "windows"
    return PLUGIN_FALLBACK.get(plugin, "misc")