import json
import logging
import re
from collections import Counter

from ..paths import TRACE_LOG
from .plugin_base import PostprocessContext

logger = logging.getLogger(__name__)

# What may become a per-plugin log's filename. The value is DRAKVUF's own
# plugin name, so this is a guard on a trusted producer rather than on the
# sample -- but it is the one place a JSON field turns into a path, and
# `Path.with_name` answers anything else with a ValueError that the handler
# below does not catch, which would abort the split half-way through.
_PLUGIN_NAME = re.compile(r"^[A-Za-z0-9_]{1,64}$")

# For lines that failed to decode: DRAKVUF writes `{"Plugin":"name",...`
# without a space, and the line starts with `{`, so the upstream heuristic
# (`re.match` against `"Plugin": "..."`) matched nothing and counted every
# failure as "unknown".
_PLUGIN_HEURISTIC = re.compile(rb'"Plugin":\s*"([A-Za-z0-9_]+)"')


def split_drakvuf_log(context: PostprocessContext) -> None:
    analysis_dir = context.analysis_dir
    drakvuf_log_path = analysis_dir / TRACE_LOG
    error_path = analysis_dir / "parse_errors.log"
    error_file = None
    plugin_files = {}
    failures = Counter()

    with drakvuf_log_path.open("rb") as drakvuf_log:
        for line in drakvuf_log:
            try:
                line_s = line.strip().decode()
                obj = json.loads(line_s)

                plugin = obj.get("Plugin", "unknown")
                if not isinstance(plugin, str) or not _PLUGIN_NAME.match(plugin):
                    plugin = "unknown"

                if plugin not in plugin_files:
                    plugin_files[plugin] = (
                        drakvuf_log_path.with_name(f"{plugin}.log")
                    ).open("w")

                plugin_file = plugin_files[plugin]
                plugin_file.write(json.dumps(obj) + "\n")
            except (UnicodeDecodeError, json.JSONDecodeError):
                # Log the failure and count statistics
                match = _PLUGIN_HEURISTIC.search(line)
                if match:
                    # we've matched an ASCII word, this cannot fail
                    plugin = match.group(1).decode("ascii")
                else:
                    plugin = "unknown"

                failures[plugin] += 1
                if not error_file:
                    error_file = error_path.open("wb")
                error_file.write(line)

    for plugin_file in plugin_files.values():
        plugin_file.close()

    if error_file:
        error_file.close()

    for plugin, count in failures.items():
        logger.warning("Failed to parse %d lines generated by %s", count, plugin)
    # The raw stream is removed once split: the per-plugin logs plus
    # parse_errors.log hold every line of it, and keeping both would double a
    # trace that already exceeds the per-job result budget on its own.
    # result-schema.md 4.1 still lists trace.log as a reserved artifact and
    # needs updating to say the split replaces it.
    drakvuf_log_path.unlink()